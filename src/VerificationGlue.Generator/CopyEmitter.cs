using System.Linq;
using System.Text;

namespace VerificationGlue.Generator;

/// <summary>
/// Writes the file of one tier 3 copy, and the file of the interceptors that send direct calls to
/// copies.
/// </summary>
/// <remarks>
/// These files are written as text, not with CSharpAuthor. The copy is mostly user text with
/// <c>#line</c> directives, and it repeats the source file's using directives, aliases and
/// namespace nesting, which CSharpAuthor 2.0.0 does not write.
/// </remarks>
internal static class CopyEmitter
{
    public const char PathMarker = '\u0001';

    private const string Header = "// <auto-generated/>\n#nullable enable\n#pragma warning disable\n";

    public static string Copy(MethodModel method, string projectDirectory)
    {
        var text = new StringBuilder(Header);
        var closers = new StringBuilder();
        foreach (var ns in method.Namespaces)
        {
            if (ns.Name is not null)
            {
                text.Append("namespace ").Append(ns.Name).Append(ns.FileScoped ? ";\n" : "\n{\n");
                if (!ns.FileScoped)
                {
                    closers.Insert(0, "}\n");
                }
            }

            foreach (var directive in ns.Usings)
            {
                text.Append(directive).Append('\n');
            }
        }

        foreach (var type in method.Types)
        {
            text.Append(PartialDeclaration(type.Keyword)).Append(' ').Append(type.Name).Append("\n{\n");
            closers.Insert(0, "}\n");
        }

        text.Append(method.Signature).Append(ResolvePaths(method.Body, projectDirectory)).Append('\n').Append(closers);
        return text.ToString();
    }

    public static string Redirects(FileRedirects file)
    {
        var text = new StringBuilder(Header).Append(InterceptorEmitter.InterceptsLocationDeclaration);
        text.Append("namespace ").Append(InterceptorEmitter.GeneratedNamespace).Append("\n{\n    file static class Redirects\n    {\n");
        foreach (var redirect in file.Redirects)
        {
            text.Append("        [global::System.Runtime.CompilerServices.InterceptsLocation(")
                .Append(redirect.LocationVersion).Append(", ").Append(CopyBuilder.Literal(redirect.LocationData)).Append(")]\n")
                .Append("        public static ").Append(redirect.ReturnType ?? "void").Append(' ')
                .Append("Redirect_").Append(redirect.Line).Append('_').Append(redirect.Column).Append('(');

            var parameters = redirect.Parameters.Select((parameter, index) =>
                (index == 0 && redirect.Kind == RedirectKind.Extension ? "this " : "") + Prefix(parameter.RefKind) + parameter.Type + " p" + index).ToList();
            if (redirect.Kind == RedirectKind.Instance)
            {
                parameters.Insert(0, "this " + redirect.ContainingType + " @this");
            }

            var arguments = string.Join(", ", redirect.Parameters.Select((parameter, index) => Argument(parameter.RefKind) + "p" + index));
            var receiver = redirect.Kind == RedirectKind.Instance ? "@this" : redirect.ContainingType;
            text.Append(string.Join(", ", parameters)).Append(") => ")
                .Append(receiver).Append('.').Append(redirect.Name).Append(Shared.VerifyRewriteRules.Suffix)
                .Append('(').Append(arguments).Append(");\n\n");
        }

        return text.Append("    }\n}\n").ToString();
    }

    /// <summary>Replaces each marked path with the literal path that a message shows.</summary>
    private static string ResolvePaths(string body, string projectDirectory)
    {
        var text = new StringBuilder(body.Length);
        var position = 0;
        while (true)
        {
            var start = body.IndexOf(PathMarker, position);
            if (start < 0)
            {
                return text.Append(body, position, body.Length - position).ToString();
            }

            var end = body.IndexOf(PathMarker, start + 1);
            text.Append(body, position, start - position);
            text.Append(CopyBuilder.Literal(InterceptorEmitter.DisplayPath(body.Substring(start + 1, end - start - 1), projectDirectory)));
            position = end + 1;
        }
    }

    /// <summary><c>static</c>, <c>readonly</c> and <c>ref</c> go before <c>partial</c>, and the type keyword after it.</summary>
    private static string PartialDeclaration(string keyword)
    {
        var parts = keyword.Split(' ');
        var modifiers = parts.Where(part => part is "static" or "readonly" or "ref");
        var rest = parts.Where(part => part is not ("static" or "readonly" or "ref"));
        return string.Join(" ", modifiers.Concat(new[] { "partial" }).Concat(rest));
    }

    private static string Prefix(string refKind) => refKind.Length == 0 ? "" : refKind + " ";

    private static string Argument(string refKind) => refKind switch
    {
        "" => "",
        "ref readonly" => "in ",
        _ => refKind + " ",
    };
}
