using System.Globalization;
using System.Linq;
using System.Text;

namespace VerificationGlue.Generator;

/// <summary>
/// Writes the interceptors of the <c>Verify(() =&gt; ...)</c> and <c>Check(() =&gt; ...)</c> calls of one
/// source file, and their checks. The checks go in the namespace of their call with the using
/// directives of the file, in a <c>file</c> class that the interceptors in this file can reach.
/// </summary>
internal static class LambdaEmitter
{
    private const string Runtime = "global::VerificationGlue.VerifyFailure";

    public static bool IsLambda(CallModel call) => call.Kind is CallKind.VerifyLambda or CallKind.CheckLambda;

    public static string HintName(string path) => InterceptorEmitter.HintName(path).Replace(".Interceptors.g.cs", ".Lambdas.g.cs");

    public static string Emit(FileCalls file)
    {
        var calls = file.Calls.Where(IsLambda).ToList();
        var text = new StringBuilder("// <auto-generated/>\n#nullable disable\n#pragma warning disable\n");
        foreach (var directive in calls[0].Lambda!.FileUsings)
        {
            text.Append(directive).Append('\n');
        }

        text.Append(InterceptorEmitter.InterceptsLocationDeclaration);

        var classes = calls.Where(call => call.Lambda!.Members is not null)
            .GroupBy(call => (call.Lambda!.Namespace, Usings: string.Join("\n", call.Lambda.NamespaceUsings)))
            .Select((group, index) => (group.Key, Name: "VerifyLambdas" + index.ToString(CultureInfo.InvariantCulture), Calls: group.ToList()))
            .ToList();

        text.Append("namespace ").Append(InterceptorEmitter.GeneratedNamespace).Append("\n{\n")
            .Append("    file static class LambdaInterceptors\n    {\n");
        foreach (var call in calls)
        {
            var site = Site(call);
            var path = CopyBuilder.Literal(InterceptorEmitter.DisplayPath(call.MappedPath, file.ProjectDirectory));
            var line = call.MappedLine.ToString(CultureInfo.InvariantCulture);
            var check = call.Kind == CallKind.CheckLambda;
            var lambda = call.Lambda!;
            var fallback = $"{Runtime}.{(check ? "Check" : "Verify")}(condition, " +
                (lambda.Members is null && lambda.Expression.Length == 0 ? "expression" : CopyBuilder.Literal(lambda.Expression)) + ", " +
                (call.Message is null ? "null" : CopyBuilder.Literal(call.Message)) + $", {path}, {line});";

            text.Append("        [global::System.Runtime.CompilerServices.InterceptsLocation(")
                .Append(call.LocationVersion.ToString(CultureInfo.InvariantCulture)).Append(", ").Append(CopyBuilder.Literal(call.LocationData)).Append(")]\n")
                .Append("        public static void ").Append(call.Kind).Append('_').Append(site)
                .Append("(global::System.Func<bool> condition, string? expression = null)\n        {\n");
            if (lambda.Members is null)
            {
                text.Append("            ").Append(fallback).Append("\n        }\n\n");
                continue;
            }

            var owner = classes.First(entry => entry.Calls.Contains(call));
            text.Append("            if (!").Append(owner.Key.Namespace is null ? "global::" : "global::" + owner.Key.Namespace + ".").Append(owner.Name).Append('.')
                .Append(LambdaBuilder.MethodName(call.Kind, site)).Append("(condition.Target, ").Append(path).Append("))\n            {\n")
                .Append("                ").Append(fallback).Append("\n            }\n        }\n\n");
        }

        text.Append("    }\n}\n");

        foreach (var entry in classes)
        {
            var indent = entry.Key.Namespace is null ? "" : "    ";
            if (entry.Key.Namespace is not null)
            {
                text.Append("\nnamespace ").Append(entry.Key.Namespace).Append("\n{\n");
                foreach (var directive in entry.Calls[0].Lambda!.NamespaceUsings)
                {
                    text.Append(indent).Append(directive).Append('\n');
                }
            }

            text.Append(indent).Append("file static class ").Append(entry.Name).Append('\n').Append(indent).Append("{\n");
            foreach (var extension in entry.Calls.SelectMany(call => call.Lambda!.Extensions).Distinct())
            {
                foreach (var member in extension.Split('\n'))
                {
                    text.Append(member.Length == 0 ? "" : indent).Append(member).Append('\n');
                }
            }

            foreach (var call in entry.Calls)
            {
                foreach (var member in call.Lambda!.Members!.Split('\n'))
                {
                    text.Append(member.Length == 0 || member.StartsWith("#", System.StringComparison.Ordinal) ? "" : indent).Append(member).Append('\n');
                }
            }

            text.Append(indent).Append("}\n");
            if (entry.Key.Namespace is not null)
            {
                text.Append("}\n");
            }
        }

        return text.ToString();
    }

    public static string Site(CallModel call) => call.Line.ToString(CultureInfo.InvariantCulture) + "_" + call.Column.ToString(CultureInfo.InvariantCulture);
}
