using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;

namespace VerificationGlue.Generator;

/// <summary>
/// Writes the <c>VerifyEquivalent</c> comparers of a compilation into one internal class, which the
/// interceptors and the tier 3 copies call, and the interceptors of the <c>VerifyEquivalent</c>
/// calls in one file.
/// </summary>
internal static class EquivalenceEmitter
{
    public const string HintName = "VerificationGlue.Equivalence.g.cs";

    private const string Class = "global::VerificationGlue.Generated.Equivalence";
    private const string Differences = "global::VerificationGlue.EquivalenceDifferences";
    private const string Runtime = "global::VerificationGlue.VerifyFailure";

    /// <summary>
    /// The call that replaces a <c>VerifyEquivalent</c> call: the generated entry for its type, or
    /// <c>EquivalentByEquals</c> when its type has no comparer.
    /// </summary>
    public static string Call(EquivalenceModel model, string actual, string expected, string actualExpression, string expectedExpression, string path, string line) =>
        (model.Root is { } root ? $"{Class}.Verify_{root}" : $"{Runtime}.EquivalentByEquals") +
        $"({actual}, {expected}, {actualExpression}, {expectedExpression}, {path}, {line})";

    /// <summary>The comparers of every model, each type once, or null when no model walks a type.</summary>
    public static string? Emit(IEnumerable<EquivalenceModel> models)
    {
        var types = new SortedDictionary<string, ComparedType>(System.StringComparer.Ordinal);
        var roots = new SortedDictionary<string, string>(System.StringComparer.Ordinal);
        foreach (var model in models)
        {
            if (model.Root is not { } root)
            {
                continue;
            }

            foreach (var type in model.Types)
            {
                types[type.Key] = type;
            }

            roots[root] = types[root].Name;
        }

        if (types.Count == 0)
        {
            return null;
        }

        var text = new StringBuilder()
            .Append("// <auto-generated/>\n#nullable disable\n#pragma warning disable\n")
            .Append("namespace VerificationGlue.Generated\n{\n")
            .Append("    [global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]\n")
            .Append("    internal static class Equivalence\n    {\n");

        foreach (var root in roots)
        {
            text.Append("        public static void Verify_").Append(root.Key).Append('(').Append(root.Value).Append(" actual, ").Append(root.Value)
                .Append(" expected, string actualExpression, string expectedExpression, string file, int line)\n        {\n")
                .Append("            var differences = new ").Append(Differences).Append("();\n")
                .Append("            Compare_").Append(root.Key).Append("(actual, expected, \"\", differences);\n")
                .Append("            ").Append(Runtime).Append(".Equivalent(differences, actualExpression, expectedExpression, file, line);\n")
                .Append("        }\n\n");
        }

        foreach (var type in types.Values)
        {
            text.Append("        public static void Compare_").Append(type.Key).Append('(').Append(type.Name).Append(" actual, ").Append(type.Name)
                .Append(" expected, string path, ").Append(Differences).Append(" differences)\n        {\n");
            if (type.IsReference)
            {
                text.Append("            if (differences.Settled(path, actual, expected))\n            {\n                return;\n            }\n\n");
            }

            for (var index = 0; index < type.Members.Count; index++)
            {
                Member(text, type.Members[index], index);
            }

            text.Append("        }\n\n");
        }

        text.Length -= 1;
        return text.Append("    }\n}\n").ToString();
    }

    private static void Member(StringBuilder text, ComparedMember member, int index)
    {
        var name = CopyBuilder.Literal(member.Name);
        var path = $"{Differences}.Path(path, {name})";
        var number = index.ToString(CultureInfo.InvariantCulture);
        if (member.Type is null)
        {
            text.Append("            differences.Equal(path, ").Append(name).Append(", actual.").Append(member.Access).Append(", expected.").Append(member.Access).Append(");\n");
        }
        else if (member.Nullable)
        {
            text.Append("            if (actual.").Append(member.Access).Append(" is { } actual").Append(number)
                .Append(" && expected.").Append(member.Access).Append(" is { } expected").Append(number).Append(")\n            {\n")
                .Append("                Compare_").Append(member.Type).Append("(actual").Append(number).Append(", expected").Append(number).Append(", ").Append(path).Append(", differences);\n")
                .Append("            }\n            else\n            {\n")
                .Append("                differences.Equal(path, ").Append(name).Append(", actual.").Append(member.Access).Append(", expected.").Append(member.Access).Append(");\n")
                .Append("            }\n");
        }
        else
        {
            text.Append("            Compare_").Append(member.Type).Append("(actual.").Append(member.Access).Append(", expected.").Append(member.Access)
                .Append(", ").Append(path).Append(", differences);\n");
        }
    }

    /// <summary>The interceptors of the <c>VerifyEquivalent</c> calls of one file, or an empty string when it has none.</summary>
    public static string Interceptors(FileCalls file)
    {
        var calls = file.Calls.Where(call => call.Equivalence is not null).ToList();
        if (calls.Count == 0)
        {
            return "";
        }

        var text = new StringBuilder("namespace VerificationGlue.Generated\n{\n    file static class EquivalentInterceptors\n    {\n");
        var first = true;
        foreach (var call in calls)
        {
            var model = call.Equivalence!;
            var type = model.Root is null ? "T" : model.ParameterType;
            text.Append(first ? "" : "\n")
                .Append("        [global::System.Runtime.CompilerServices.InterceptsLocation(")
                .Append(call.LocationVersion.ToString(CultureInfo.InvariantCulture)).Append(", ").Append(CopyBuilder.Literal(call.LocationData)).Append(")]\n")
                .Append("        public static void VerifyEquivalent_").Append(call.Line.ToString(CultureInfo.InvariantCulture)).Append('_').Append(call.Column.ToString(CultureInfo.InvariantCulture))
                .Append(model.Root is null ? "<T>(" : "(").Append(type).Append(" actual, ").Append(type)
                .Append(" expected, string? actualExpression = null, string? expectedExpression = null)\n        {\n            ")
                .Append(Call(
                    model,
                    "actual",
                    "expected",
                    "actualExpression",
                    "expectedExpression",
                    CopyBuilder.Literal(InterceptorEmitter.DisplayPath(call.MappedPath, file.ProjectDirectory)),
                    call.MappedLine.ToString(CultureInfo.InvariantCulture)))
                .Append(";\n        }\n");
            first = false;
        }

        return text.Append("    }\n}\n").ToString();
    }
}
