using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;

namespace VerificationGlue.Generator;

/// <summary>
/// Writes the <c>VerifyEquivalent</c> and <c>CheckEquivalent</c> comparers of a compilation into
/// one internal class, which the interceptors and the tier 3 copies call, and the interceptors of
/// those calls in one file.
/// </summary>
internal static class EquivalenceEmitter
{
    public const string HintName = "VerificationGlue.Equivalence.g.cs";

    private const string Class = "global::VerificationGlue.Generated.Equivalence";
    private const string Differences = "global::VerificationGlue.EquivalenceDifferences";
    private const string Runtime = "global::VerificationGlue.VerifyFailure";

    /// <summary>
    /// The call that replaces a <c>VerifyEquivalent</c> or <c>CheckEquivalent</c> call. It passes the
    /// differences that the generated entry for its type finds, or that <c>EqualsDifferences</c>
    /// finds when its type has no comparer, to <c>Equivalent</c> or <c>CheckEquivalent</c>.
    /// </summary>
    public static string Call(EquivalenceModel model, CallKind kind, string actual, string expected, string actualExpression, string expectedExpression, string path, string line) =>
        $"{Runtime}.{(kind == CallKind.CheckEquivalent ? "CheckEquivalent" : "Equivalent")}(" +
        (model.Root is { } root ? $"{Class}.Differences_{root}" : $"{Runtime}.EqualsDifferences") +
        $"({actual}, {expected}), {actualExpression}, {expectedExpression}, {path}, {line})";

    /// <summary>The comparers of every model, each type once, or null when no model walks a type.</summary>
    public static string? Emit(IEnumerable<EquivalenceModel> models)
    {
        var types = new SortedDictionary<string, ComparedType>(System.StringComparer.Ordinal);
        var roots = new SortedDictionary<string, string>(System.StringComparer.Ordinal);
        foreach (var model in models)
        {
            if (model.Root is not { } root)
            {
                continue;
            }

            foreach (var type in model.Types)
            {
                types[type.Key] = type;
            }

            roots[root] = types[root].Name;
        }

        if (types.Count == 0)
        {
            return null;
        }

        var text = new StringBuilder()
            .Append("// <auto-generated/>\n#nullable disable\n#pragma warning disable\n")
            .Append("namespace VerificationGlue.Generated\n{\n")
            .Append("    [global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]\n")
            .Append("    internal static class Equivalence\n    {\n");

        foreach (var root in roots)
        {
            text.Append("        public static ").Append(Differences).Append(" Differences_").Append(root.Key).Append('(').Append(root.Value).Append(" actual, ").Append(root.Value)
                .Append(" expected)\n        {\n")
                .Append("            var differences = new ").Append(Differences).Append("();\n")
                .Append("            Compare_").Append(root.Key).Append("(actual, expected, \"\", differences);\n")
                .Append("            return differences;\n")
                .Append("        }\n\n");
        }

        foreach (var type in types.Values)
        {
            text.Append("        public static void Compare_").Append(type.Key).Append('(').Append(type.Name).Append(" actual, ").Append(type.Name)
                .Append(" expected, string path, ").Append(Differences).Append(" differences)\n        {\n");
            if (type.IsReference)
            {
                text.Append("            if (differences.Settled(path, actual, expected))\n            {\n                return;\n            }\n\n");
            }

            if (type.Items is { } items)
            {
                Items(text, items);
            }

            if (type.Entries is { } entries)
            {
                Entries(text, entries);
            }

            for (var index = 0; index < type.Members.Count; index++)
            {
                var member = type.Members[index];
                var name = CopyBuilder.Literal(member.Name);
                Value(
                    text,
                    "            ",
                    member.Type,
                    member.Nullable,
                    "actual." + member.Access,
                    "expected." + member.Access,
                    $"{Differences}.Path(path, {name})",
                    "path, " + name,
                    index.ToString(CultureInfo.InvariantCulture));
            }

            if (type.IsReference)
            {
                text.Append("            differences.Leave();\n");
            }

            text.Append("        }\n\n");
        }

        text.Length -= 1;
        return text.Append("    }\n}\n").ToString();
    }

    private static void Items(StringBuilder text, ComparedItems items)
    {
        if (items.Set && items.Type is null)
        {
            SetItems(text);
            return;
        }

        if (items.Set)
        {
            text.Append("            var actualItems = global::System.Linq.Enumerable.ToArray(actual);\n")
                .Append("            var expectedItems = global::System.Linq.Enumerable.ToArray(expected);\n");
            UnorderedItems(text, items, "actualItems", "expectedItems", "Length");
            return;
        }

        if (items.Unordered)
        {
            UnorderedItems(text, items, "actual", "expected", items.Count);
            return;
        }

        text.Append("            differences.ItemCount(path, actual.").Append(items.Count).Append(", expected.").Append(items.Count).Append(");\n")
            .Append("            var count = actual.").Append(items.Count).Append(" < expected.").Append(items.Count)
            .Append(" ? actual.").Append(items.Count).Append(" : expected.").Append(items.Count).Append(";\n")
            .Append("            for (var index = 0; index < count; index++)\n            {\n");
        var path = $"{Differences}.Item(path, index)";
        Value(text, "                ", items.Type, items.Nullable, "actual[index]", "expected[index]", path, path + ", \"\"", "Item");
        text.Append("            }\n");
    }

    /// <summary>
    /// Matches each expected item with the first unmatched actual item that is the same, then lists
    /// each expected item left as missing and each actual item left as extra.
    /// </summary>
    private static void UnorderedItems(StringBuilder text, ComparedItems items, string actual, string expected, string count)
    {
        var same = items.Type is null
            ? $"differences.Same({actual}[other], {expected}[index])"
            : $"differences.{(items.Nullable ? "SameNullable" : "Same")}({actual}[other], {expected}[index], Compare_{items.Type})";
        text.Append("            var matched = new bool[").Append(actual).Append('.').Append(count).Append("];\n")
            .Append("            for (var index = 0; index < ").Append(expected).Append('.').Append(count).Append("; index++)\n            {\n")
            .Append("                var found = false;\n")
            .Append("                for (var other = 0; other < ").Append(actual).Append('.').Append(count).Append(" && !found; other++)\n                {\n")
            .Append("                    if (!matched[other] && ").Append(same).Append(")\n                    {\n")
            .Append("                        matched[other] = found = true;\n")
            .Append("                    }\n                }\n\n")
            .Append("                if (!found)\n                {\n")
            .Append("                    differences.Missing(path, ").Append(expected).Append("[index]);\n")
            .Append("                }\n            }\n\n")
            .Append("            for (var index = 0; index < ").Append(actual).Append('.').Append(count).Append("; index++)\n            {\n")
            .Append("                if (!matched[index])\n                {\n")
            .Append("                    differences.Extra(path, ").Append(actual).Append("[index]);\n")
            .Append("                }\n            }\n");
    }

    /// <summary>Looks up each item of a set whose items compare with <c>Equals</c> in the other set, with that set's own comparer.</summary>
    private static void SetItems(StringBuilder text) =>
        text.Append("            foreach (var item in expected)\n            {\n")
            .Append("                if (!actual.Contains(item))\n                {\n")
            .Append("                    differences.Missing(path, item);\n")
            .Append("                }\n            }\n\n")
            .Append("            foreach (var item in actual)\n            {\n")
            .Append("                if (!expected.Contains(item))\n                {\n")
            .Append("                    differences.Extra(path, item);\n")
            .Append("                }\n            }\n");

    /// <summary>
    /// Compares the value of each expected key that the actual dictionary has, then lists each
    /// expected entry whose key it lacks as missing and each actual entry whose key the expected
    /// dictionary lacks as extra. Each lookup uses the key comparer of the dictionary it reads.
    /// </summary>
    private static void Entries(StringBuilder text, ComparedEntries entries)
    {
        var path = $"{Differences}.Entry(path, entry.Key)";
        text.Append("            foreach (var entry in expected)\n            {\n")
            .Append("                if (actual.TryGetValue(entry.Key, out var actualValue))\n                {\n");
        Value(text, "                    ", entries.Type, entries.Nullable, "actualValue", "entry.Value", path, path + ", \"\"", "Entry");
        text.Append("                }\n                else\n                {\n")
            .Append("                    differences.MissingEntry(path, entry.Key, entry.Value);\n")
            .Append("                }\n            }\n\n")
            .Append("            foreach (var entry in actual)\n            {\n")
            .Append("                if (!expected.ContainsKey(entry.Key))\n                {\n")
            .Append("                    differences.ExtraEntry(path, entry.Key, entry.Value);\n")
            .Append("                }\n            }\n");
    }

    /// <summary>
    /// Compares one member or item: with the comparer of its type, or with <c>Equals</c> when it has
    /// none. <paramref name="equalArguments"/> are the path and member arguments of <c>Equal</c>.
    /// </summary>
    private static void Value(StringBuilder text, string indent, string? type, bool nullable, string actual, string expected, string path, string equalArguments, string suffix)
    {
        if (type is null)
        {
            text.Append(indent).Append("differences.Equal(").Append(equalArguments).Append(", ").Append(actual).Append(", ").Append(expected).Append(");\n");
        }
        else if (nullable)
        {
            text.Append(indent).Append("if (").Append(actual).Append(" is { } actual").Append(suffix)
                .Append(" && ").Append(expected).Append(" is { } expected").Append(suffix).Append(")\n")
                .Append(indent).Append("{\n")
                .Append(indent).Append("    Compare_").Append(type).Append("(actual").Append(suffix).Append(", expected").Append(suffix).Append(", ").Append(path).Append(", differences);\n")
                .Append(indent).Append("}\n")
                .Append(indent).Append("else\n")
                .Append(indent).Append("{\n")
                .Append(indent).Append("    differences.Equal(").Append(equalArguments).Append(", ").Append(actual).Append(", ").Append(expected).Append(");\n")
                .Append(indent).Append("}\n");
        }
        else
        {
            text.Append(indent).Append("Compare_").Append(type).Append('(').Append(actual).Append(", ").Append(expected)
                .Append(", ").Append(path).Append(", differences);\n");
        }
    }

    /// <summary>The interceptors of the <c>VerifyEquivalent</c> and <c>CheckEquivalent</c> calls of one file, or an empty string when it has none.</summary>
    public static string Interceptors(FileCalls file)
    {
        var calls = file.Calls.Where(call => call.Equivalence is not null).ToList();
        if (calls.Count == 0)
        {
            return "";
        }

        var text = new StringBuilder("namespace VerificationGlue.Generated\n{\n    file static class EquivalentInterceptors\n    {\n");
        var first = true;
        foreach (var call in calls)
        {
            var model = call.Equivalence!;
            var type = model.Root is null ? "T" : model.ParameterType;
            text.Append(first ? "" : "\n")
                .Append("        [global::System.Runtime.CompilerServices.InterceptsLocation(")
                .Append(call.LocationVersion.ToString(CultureInfo.InvariantCulture)).Append(", ").Append(CopyBuilder.Literal(call.LocationData)).Append(")]\n")
                .Append("        public static void ").Append(call.Kind.ToString()).Append('_').Append(call.Line.ToString(CultureInfo.InvariantCulture)).Append('_').Append(call.Column.ToString(CultureInfo.InvariantCulture))
                .Append(model.Root is null ? "<T>(" : "(").Append(type).Append(" actual, ").Append(type)
                .Append(" expected, ").Append(model.OptionsType is null ? "" : model.OptionsType + " options, ")
                .Append("string? actualExpression = null, string? expectedExpression = null)\n        {\n            ")
                .Append(Call(
                    model,
                    call.Kind,
                    "actual",
                    "expected",
                    "actualExpression",
                    "expectedExpression",
                    CopyBuilder.Literal(InterceptorEmitter.DisplayPath(call.MappedPath, file.ProjectDirectory)),
                    call.MappedLine.ToString(CultureInfo.InvariantCulture)))
                .Append(";\n        }\n");
            first = false;
        }

        return text.Append("    }\n}\n").ToString();
    }
}
