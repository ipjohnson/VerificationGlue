using System.IO;
using System.Linq;
using System.Text;
using CSharpAuthor.Collections;

namespace VerificationGlue.Mocks.Generator;

/// <summary>
/// One <c>Arg.Any</c> or <c>Arg.Is</c> call passed directly to a mock member, with the ordinal of
/// the parameter it is passed to.
/// </summary>
internal sealed record ArgSite(int Position, ArgKind Kind, int Ordinal, int LocationVersion, string LocationData);

/// <summary>The <c>Arg</c> call sites of one source file.</summary>
internal sealed record ArgFile(string FilePath, EquatableArray<ArgSite> Sites);

/// <summary>
/// Writes the interceptors that pass each <c>Arg</c> matcher the ordinal of its parameter. Without
/// them, a matcher goes to the first argument that holds a default value, which is wrong for
/// <c>calc.Add(0, Arg.Any&lt;int&gt;())</c>.
/// </summary>
internal static class ArgInterceptorEmitter
{
    // The compiler recognises InterceptsLocationAttribute by name and the BCL does not ship it, so
    // each file declares its own copy as a file-local type.
    private const string InterceptsLocationDeclaration =
        "namespace System.Runtime.CompilerServices\n{\n" +
        "    [global::System.AttributeUsage(global::System.AttributeTargets.Method, AllowMultiple = true)]\n" +
        "    file sealed class InterceptsLocationAttribute(int version, string data) : global::System.Attribute\n    {\n    }\n}\n";

    private const string Arg = "global::VerificationGlue.Mocks.Arg";

    /// <summary>A hint name that is unique per source path, since two folders can hold files of the same name.</summary>
    public static string HintName(string path)
    {
        unchecked
        {
            var hash = 2166136261u;
            foreach (var character in path)
            {
                hash = (hash ^ character) * 16777619u;
            }

            return $"{Path.GetFileNameWithoutExtension(path)}.{hash:x8}.ArgInterceptors.g.cs";
        }
    }

    public static string Emit(ArgFile file)
    {
        var text = new StringBuilder("// <auto-generated/>\n#nullable enable\n#pragma warning disable\n");
        text.Append(InterceptsLocationDeclaration);
        text.Append("namespace ").Append(MockEmitter.GeneratedNamespace).Append("\n{\n");
        text.Append("    file static class ArgInterceptors\n    {\n");

        foreach (var group in file.Sites.GroupBy(site => (site.Kind, site.Ordinal)).OrderBy(group => group.Key.Kind).ThenBy(group => group.Key.Ordinal))
        {
            foreach (var site in group.OrderBy(site => site.Position))
            {
                text.Append("        [global::System.Runtime.CompilerServices.InterceptsLocation(")
                    .Append(site.LocationVersion).Append(", \"").Append(site.LocationData).Append("\")]\n");
            }

            var ordinal = group.Key.Ordinal;
            text.Append("        public static ").Append(group.Key.Kind switch
            {
                ArgKind.Any => $"ref T Any_{ordinal}<T>() => ref {Arg}.AnyAt<T>({ordinal});",
                ArgKind.IsPredicate => $"ref T IsPredicate_{ordinal}<T>(global::System.Func<T, bool> predicate) => ref {Arg}.IsAt<T>({ordinal}, predicate);",
                _ => $"ref T IsValue_{ordinal}<T>(T value) => ref {Arg}.IsAt<T>({ordinal}, value);",
            }).Append('\n');
        }

        text.Append("    }\n}\n");
        return text.ToString();
    }
}
