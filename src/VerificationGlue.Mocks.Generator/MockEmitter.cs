using System.Collections.Generic;
using System.Linq;
using System.Text;
using CSharpAuthor;
using CSharpAuthor.Collections;
using Microsoft.CodeAnalysis.CSharp;

namespace VerificationGlue.Mocks.Generator;

/// <summary>Writes the mock class for one <see cref="MockModel"/>.</summary>
internal static class MockEmitter
{
    public const string GeneratedNamespace = "VerificationGlue.Mocks.Generated";

    private const string Adapter = "this._adapter";

    public static string Emit(MockModel model)
    {
        var file = new CSharpFileDefinition(GeneratedNamespace);
        var type = file.AddClass(model.MockName);
        type.Modifiers = ComponentModifier.Internal | ComponentModifier.Sealed;
        if (model.IsObsolete)
        {
            type.AddAttribute(typeof(System.ObsoleteAttribute));
        }

        foreach (var parameter in model.TypeParameters)
        {
            type.AddGenericParameter(parameter.Name);
            Constrain(type.AddConstraint(parameter.Name), parameter);
        }

        type.AddBaseType(model.Type);
        type.AddBaseType(KnownTypes.IMock);

        var adapter = type.AddField(KnownTypes.MockAdapter, "_adapter");
        adapter.Modifiers = ComponentModifier.Private | ComponentModifier.Readonly;
        adapter.InitializeValue = new CodeOutputComponent("new " + Render(KnownTypes.MockAdapter) + "(" + Literal(model.MockName) + ")") { Indented = false };

        var adapterProperty = new PropertyDefinition(KnownTypes.MockAdapter, Explicit(KnownTypes.IMock, "Adapter"))
        {
            Modifiers = ComponentModifier.NoAccessibility,
        };
        adapterProperty.Set = null;
        adapterProperty.Get.LambdaSyntax = true;
        adapterProperty.Get.Return(new CodeOutputComponent(Adapter));
        type.AddComponent(adapterProperty);

        foreach (var member in model.Members)
        {
            switch (member.Kind)
            {
                case MemberKind.Method:
                    EmitMethod(type, member);
                    break;
                case MemberKind.Property:
                case MemberKind.Indexer:
                    EmitProperty(type, member);
                    break;
                case MemberKind.Event:
                    EmitEvent(type, member);
                    break;
            }
        }

        var context = new OutputContext(new OutputContextOptions { TypeOutputMode = TypeOutputMode.Global, GenerateDocumentation = false });
        file.WriteOutput(context);

        var header = new StringBuilder("// <auto-generated/>\n");
        foreach (var alias in model.ExternAliases)
        {
            header.Append("extern alias ").Append(alias).Append(";\n");
        }

        header.Append("#nullable enable\n#pragma warning disable\n");
        return header + context.Output() + "\n" + SurfaceEmitter.Emit(model);
    }

    private static void Constrain(ConstraintDefinition constraint, TypeParameterModel parameter)
    {
        switch (parameter.Primary)
        {
            case "class":
                constraint.Class();
                break;
            case "class?":
                constraint.Class(nullable: true);
                break;
            case "struct":
                constraint.Struct();
                break;
            case "unmanaged":
                constraint.Unmanaged();
                break;
            case "notnull":
                constraint.NotNull();
                break;
            case "default":
                constraint.Default();
                break;
        }

        foreach (var type in parameter.Types)
        {
            constraint.Implements(type);
        }

        if (parameter.HasConstructor)
        {
            constraint.DefaultConstructor();
        }
    }

    private static void EmitMethod(ClassDefinition type, MockMemberModel member)
    {
        var method = type.AddMethod(member.Name);
        method.InterfaceImplementation = member.Interface;
        var returnType = member.Type ?? TypeDefinition.Get(typeof(void));
        method.SetReturnType(Prefixed(member, returnType));

        foreach (var parameter in member.TypeParameters)
        {
            method.AddGenericParameter(new TypeParameterDefinition(parameter.Name));
            Constrain(method.AddConstraint(parameter.Name), parameter);
        }

        foreach (var parameter in member.Parameters)
        {
            AddParameter(method, parameter);
        }

        if (member.Unsupported != null)
        {
            method.AddCode(Throw(member) + ";");
            return;
        }

        var typeArguments = member.TypeParameters.Count == 0
            ? "null"
            : "new global::System.Type[] { " + string.Join(", ", member.TypeParameters.Select(p => "typeof(" + Escape(p.Name) + ")")) + " }";
        var call = Call(member, member.Name, typeArguments, "__args");
        var writeBacks = member.Parameters
            .Select((parameter, index) => (parameter, index))
            .Where(pair => pair.parameter.Modifier is ParameterModifier.Ref or ParameterModifier.Out)
            .ToList();
        var byRef = member.ReturnKind == ReturnKind.Ref ? "ref " : "";

        method.AddCode("var __args = " + Arguments(member.Parameters) + ";");
        if (member.ReturnKind == ReturnKind.Void)
        {
            method.AddCode(call + ";");
        }
        else if (writeBacks.Count == 0)
        {
            method.AddCode("return " + byRef + call + ";");
            return;
        }
        else
        {
            method.AddCode((byRef.Length > 0 ? "ref var" : "var") + " __result = " + byRef + call + ";");
        }

        foreach (var (parameter, index) in writeBacks)
        {
            method.AddCode(Escape(parameter.Name) + " = (" + Render(parameter.Type) + ")__args[" + index + "]!;");
        }

        if (member.ReturnKind != ReturnKind.Void)
        {
            method.AddCode("return " + byRef + "__result;");
        }
    }

    private static void EmitProperty(ClassDefinition type, MockMemberModel member)
    {
        var name = member.Kind == MemberKind.Indexer ? Render(member.Interface) + ".this" : Explicit(member.Interface, member.Name);
        var getterName = "get_" + member.Name;
        var setterName = "set_" + member.Name;
        var arguments = Arguments(member.Parameters);
        var propertyType = Prefixed(member, member.Type!);

        var getter = member.Unsupported != null
            ? Throw(member)
            : (member.ReturnKind == ReturnKind.Ref ? "ref " : "") + Call(member, getterName, "null", arguments);
        var setter = member.Unsupported != null
            ? Throw(member)
            : $"{Adapter}.SetProperty({(member.HasGetter ? member.Id : -1)}, {member.Id + 1}, {Literal(setterName)}, {arguments}, value)";

        if (!member.HasGetter)
        {
            var parameters = string.Join(", ", member.Parameters.Select(ParameterText));
            var raw = new RawLines();
            raw.Add(Render(propertyType) + " " + name + (member.Kind == MemberKind.Indexer ? "[" + parameters + "]" : ""));
            raw.Add("{");
            raw.Add("    " + (member.IsInit ? "init" : "set") + " => " + setter + ";");
            raw.Add("}");
            type.AddComponent(raw);
            return;
        }

        var property = new PropertyDefinition(propertyType, name) { Modifiers = ComponentModifier.NoAccessibility };
        foreach (var parameter in member.Parameters)
        {
            property.AddIndexParameter(parameter.Type, parameter.Name);
            property.IndexParameters[property.IndexParameters.Count - 1].Modifier = parameter.Modifier;
            property.IndexParameters[property.IndexParameters.Count - 1].IsParams = parameter.IsParams;
        }

        property.Get.LambdaSyntax = true;
        property.Get.Return(new CodeOutputComponent(getter));

        if (member.HasSetter)
        {
            property.Set = new PropertyMethodDefinition { LambdaSyntax = true, IsInit = member.IsInit };
            property.Set.AddIndentedStatement(new CodeOutputComponent(setter));
        }
        else
        {
            property.Set = null;
        }

        type.AddComponent(property);
    }

    private static void EmitEvent(ClassDefinition type, MockMemberModel member)
    {
        var field = "__event_" + member.Id;
        type.AddField(member.Type!.MakeNullable(), field).Modifiers = ComponentModifier.Private;

        var @event = new EventDefinition(member.Type!, Explicit(member.Interface, member.Name))
        {
            Modifiers = ComponentModifier.NoAccessibility,
        };

        var addCall = $"{Adapter}.EventAdd({member.Id}, {Literal("add_" + member.Name)}, value, out var __raise)";
        if (member.CanRaise)
        {
            var raise = @event.Add.If(addCall);
            var arguments = new List<string>();
            for (var index = 0; index < member.Parameters.Count; index++)
            {
                var parameter = member.Parameters[index];
                raise.AddCode($"var {parameter.Name} = ({Render(parameter.Type)})__raise[{index}]!;");
                arguments.Add(ModifierText(parameter.Modifier) + parameter.Name);
            }

            raise.AddCode($"var __handler = this.{field};");
            raise.If("__handler != null").AddCode($"__handler.Invoke({string.Join(", ", arguments)});");
            raise.Else().AddCode($"this.{field} += value;");
        }
        else
        {
            @event.Add.If(addCall).AddCode(
                $"throw new global::System.NotSupportedException({Literal(member.Name + " cannot be raised, because its delegate takes a ref struct or a pointer.")});");
            @event.Add.AddCode($"this.{field} += value;");
        }

        @event.Remove.AddCode($"{Adapter}.EventRemove({member.Id + 1}, {Literal("remove_" + member.Name)}, value);");
        @event.Remove.AddCode($"this.{field} -= value;");
        type.AddComponent(@event);
    }

    private static void AddParameter(MethodDefinition method, ParameterModel parameter)
    {
        if (parameter.IsScoped)
        {
            method.AddParameter(new PrefixedTypeDefinition("scoped " + ModifierText(parameter.Modifier), parameter.Type), parameter.Name);
            return;
        }

        var definition = method.AddParameter(parameter.Type, parameter.Name);
        definition.Modifier = parameter.Modifier;
        definition.IsParams = parameter.IsParams;
    }

    private static ITypeDefinition Prefixed(MockMemberModel member, ITypeDefinition type)
    {
        var prefix = (member.IsUnsafe ? "unsafe " : "") + member.RefReturn switch
        {
            RefReturn.Ref => "ref ",
            RefReturn.RefReadonly => "ref readonly ",
            _ => "",
        };
        return prefix.Length == 0 ? type : new PrefixedTypeDefinition(prefix, type);
    }

    private static string Call(MockMemberModel member, string name, string typeArguments, string arguments)
    {
        var head = $"{Adapter}.";
        var tail = $"({member.Id}, {Literal(name)}, {typeArguments}, {arguments})";
        return member.ReturnKind switch
        {
            ReturnKind.Void => head + "CallVoid" + tail,
            ReturnKind.Task => head + "CallTask" + tail,
            ReturnKind.TaskOfT => head + "CallTask<" + Render(member.AwaitedType!) + ">" + tail,
            ReturnKind.ValueTask => head + "CallValueTask" + tail,
            ReturnKind.ValueTaskOfT => head + "CallValueTask<" + Render(member.AwaitedType!) + ">" + tail,
            ReturnKind.Ref => head + "CallRef<" + Render(member.Type!) + ">" + tail,
            ReturnKind.Value when member.ReturnsMock => head + "CallMock<" + Render(member.Type!) + ">" + tail,
            _ => head + "Call<" + Render(member.Type!) + ">" + tail,
        };
    }

    private static string Arguments(EquatableArray<ParameterModel> parameters)
    {
        if (parameters.Count == 0)
        {
            return "global::System.Array.Empty<object?>()";
        }

        var items = parameters.Select(p => p.Modifier == ParameterModifier.Out ? "default(" + Render(p.Type) + ")" : Escape(p.Name));
        return "new object?[] { " + string.Join(", ", items) + " }";
    }

    private static string Throw(MockMemberModel member) =>
        $"throw new global::System.NotSupportedException({Literal(member.Name + " cannot be mocked: " + member.Unsupported + ".")})";

    private static string ParameterText(ParameterModel parameter) =>
        (parameter.IsScoped ? "scoped " : "") + ModifierText(parameter.Modifier) + (parameter.IsParams ? "params " : "") +
        Render(parameter.Type) + " " + Escape(parameter.Name);

    private static string ModifierText(ParameterModifier modifier) => modifier switch
    {
        ParameterModifier.Ref => "ref ",
        ParameterModifier.Out => "out ",
        ParameterModifier.In => "in ",
        ParameterModifier.RefReadOnly => "ref readonly ",
        _ => "",
    };

    private static string Explicit(ITypeDefinition contract, string name) => Render(contract) + "." + Escape(name);

    internal static string Escape(string name) =>
        SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None || SyntaxFacts.GetContextualKeywordKind(name) == SyntaxKind.FieldKeyword
            ? "@" + name
            : name;

    internal static string Literal(string text) => SymbolDisplay.FormatLiteral(text, quote: true);

    internal static string Render(ITypeDefinition type)
    {
        var builder = new StringBuilder();
        type.WriteTypeName(builder, TypeOutputMode.Global);
        return builder.ToString();
    }
}
