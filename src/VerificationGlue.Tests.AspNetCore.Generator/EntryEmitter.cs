using System.Text;
using CSharpAuthor;
using Microsoft.CodeAnalysis.CSharp;

namespace VerificationGlue.Tests.AspNetCore.Generator;

/// <summary>
/// Writes the part of an entry class that implements <c>IWebAppEntry</c>: the app's name, and
/// <c>Run</c>, which calls the app's entry point through an <c>UnsafeAccessor</c> that names the
/// entry point's type as a string.
/// </summary>
internal static class EntryEmitter
{
    private static readonly ITypeDefinition IWebAppEntry = TypeDefinition.Get("VerificationGlue.Tests.AspNetCore", "IWebAppEntry");
    private static readonly ITypeDefinition UnsafeAccessor = TypeDefinition.Get("System.Runtime.CompilerServices", "UnsafeAccessor");
    private static readonly ITypeDefinition UnsafeAccessorKind = TypeDefinition.Get("System.Runtime.CompilerServices", "UnsafeAccessorKind");
    private static readonly ITypeDefinition UnsafeAccessorType = TypeDefinition.Get("System.Runtime.CompilerServices", "UnsafeAccessorType");

    public static string HintName(EntryClassModel entry) =>
        (entry.Namespace is null ? "" : entry.Namespace + ".") + entry.Name + ".WebAppEntry.g.cs";

    public static string ReturnType(EntryReturn kind) => kind switch
    {
        EntryReturn.Void => "void",
        EntryReturn.Int => "int",
        EntryReturn.Task => "global::System.Threading.Tasks.Task",
        _ => "global::System.Threading.Tasks.Task<int>",
    };

    public static string Emit(EntryClassModel entry, EntryPointModel entryPoint)
    {
        var call = entryPoint.HasArgs ? "EntryPoint(null, args)" : "EntryPoint(null)";
        var text = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
        if (entry.Namespace is not null)
        {
            text.Append("namespace ").Append(entry.Namespace).Append(";\n");
        }

        text.Append('\n');
        text.Append("partial class ").Append(entry.Name).Append(" : ").Append(Render(IWebAppEntry)).Append('\n');
        text.Append("{\n");
        text.Append("    public static string ApplicationName => ").Append(Literal(entry.AssemblyName)).Append(";\n\n");
        text.Append("    public static int Run(string[] args)\n    {\n");
        text.Append(entryPoint.Return switch
        {
            EntryReturn.Void => $"        {call};\n        return 0;\n",
            EntryReturn.Int => $"        return {call};\n",
            EntryReturn.Task => $"        {call}.GetAwaiter().GetResult();\n        return 0;\n",
            _ => $"        return {call}.GetAwaiter().GetResult();\n",
        });
        text.Append("    }\n\n");
        text.Append("    [").Append(Render(UnsafeAccessor)).Append('(').Append(Render(UnsafeAccessorKind)).Append(".StaticMethod, Name = ")
            .Append(Literal(entryPoint.MethodName)).Append(")]\n");
        text.Append("    private static extern ").Append(ReturnType(entryPoint.Return)).Append(" EntryPoint(\n");
        text.Append("        [").Append(Render(UnsafeAccessorType)).Append('(').Append(Literal(entryPoint.TypeName + ", " + entry.AssemblyName)).Append(")] object? type");
        text.Append(entryPoint.HasArgs ? ",\n        string[] args);\n" : ");\n");
        text.Append("}\n");
        return text.ToString();
    }

    private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, quote: true);

    private static string Render(ITypeDefinition type)
    {
        var builder = new StringBuilder();
        type.WriteTypeName(builder, TypeOutputMode.Global);
        return builder.ToString();
    }
}
