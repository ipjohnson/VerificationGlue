using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;

namespace Glue.Mocks.Generator
{
    internal static class Emitter
    {
        private const string Adapter = "global::Glue.Mocks.MockAdapter";

        public static string EmitMock(MockModel model)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("#nullable enable");
            sb.AppendLine("#pragma warning disable");
            sb.AppendLine("namespace Glue.Mocks.Generated");
            sb.AppendLine("{");
            sb.AppendLine($"    internal sealed class {model.MockName} : {model.Type}, global::Glue.Mocks.IMock");
            sb.AppendLine("    {");
            sb.AppendLine($"        private readonly {Adapter} _adapter = new {Adapter}(\"{model.MockName}\");");
            sb.AppendLine($"        {Adapter} global::Glue.Mocks.IMock.Adapter => _adapter;");

            var id = 0;

            foreach (var member in model.Members)
            {
                sb.AppendLine();

                switch (member.Kind)
                {
                    case MemberKind.Method:
                        EmitMethod(sb, member, id++);
                        break;
                    case MemberKind.Property:
                    case MemberKind.Indexer:
                        EmitProperty(sb, member, id);
                        id += 2;
                        break;
                    case MemberKind.Event:
                        EmitEvent(sb, member, id);
                        id += 2;
                        break;
                }
            }

            sb.AppendLine("    }");
            sb.AppendLine("}");
            return sb.ToString();
        }

        private static string Head(MemberModel member, string name) =>
            member.IsOverride ? $"public override {member.ReturnType} {name}" : $"{member.ReturnType} {member.ContainingType}.{name}";

        private static string ParameterList(MemberModel member) =>
            string.Join(
                ", ",
                member.Parameters.Select(p =>
                    (p.RefKind switch { 1 => "ref ", 2 => "out ", 3 => "in ", 4 => "ref readonly ", _ => "" }) + p.Type + " " + p.Name
                )
            );

        private static string ArgumentArray(IEnumerable<ParameterModel> parameters)
        {
            var items = parameters.Select(p => p.RefKind == 2 ? $"default({p.Type})" : p.Name).ToArray();
            return items.Length == 0 ? "global::System.Array.Empty<object?>()" : "new object?[] { " + string.Join(", ", items) + " }";
        }

        private static string Call(MemberModel member, int id, string name, string typeArgs, string args) =>
            member.ReturnKind switch
            {
                ReturnKind.Void => $"_adapter.CallVoid({id}, \"{name}\", {typeArgs}, {args})",
                ReturnKind.Task => $"_adapter.CallTask({id}, \"{name}\", {typeArgs}, {args})",
                ReturnKind.TaskOfT => $"_adapter.CallTask<{member.AwaitedType}>({id}, \"{name}\", {typeArgs}, {args})",
                ReturnKind.ValueTask => $"_adapter.CallValueTask({id}, \"{name}\", {typeArgs}, {args})",
                ReturnKind.ValueTaskOfT => $"_adapter.CallValueTask<{member.AwaitedType}>({id}, \"{name}\", {typeArgs}, {args})",
                _ => $"_adapter.Call<{member.ReturnType}>({id}, \"{name}\", {typeArgs}, {args})",
            };

        private static void EmitMethod(StringBuilder sb, MemberModel member, int id)
        {
            var generics = member.TypeParameters.Length == 0 ? "" : "<" + string.Join(", ", member.TypeParameters) + ">";
            sb.AppendLine($"        {Head(member, member.Name + generics)}({ParameterList(member)})");
            sb.AppendLine("        {");

            if (member.Unsupported != null)
            {
                sb.AppendLine($"            throw new global::System.NotSupportedException(\"{member.Name} cannot be mocked: {member.Unsupported}.\");");
                sb.AppendLine("        }");
                return;
            }

            var typeArgs =
                member.TypeParameters.Length == 0
                    ? "null"
                    : "new global::System.Type[] { " + string.Join(", ", member.TypeParameters.Select(t => $"typeof({t})")) + " }";

            sb.AppendLine($"            var __args = {ArgumentArray(member.Parameters)};");
            var call = Call(member, id, member.Name, typeArgs, "__args");
            sb.AppendLine(member.ReturnKind == ReturnKind.Void ? $"            {call};" : $"            var __result = {call};");

            for (var i = 0; i < member.Parameters.Length; i++)
            {
                var p = member.Parameters[i];

                if (p.RefKind == 1 || p.RefKind == 2)
                {
                    sb.AppendLine($"            {p.Name} = ({p.Type})__args[{i}]!;");
                }
            }

            if (member.ReturnKind != ReturnKind.Void)
            {
                sb.AppendLine("            return __result;");
            }

            sb.AppendLine("        }");
        }

        private static void EmitProperty(StringBuilder sb, MemberModel member, int id)
        {
            var name = member.Kind == MemberKind.Indexer ? $"this[{ParameterList(member)}]" : member.Name;
            var args = ArgumentArray(member.Parameters);
            var getterId = member.HasGetter ? id : -1;

            sb.AppendLine($"        {Head(member, name)}");
            sb.AppendLine("        {");

            if (member.HasGetter)
            {
                sb.AppendLine($"            get => {Call(member, id, "get_" + member.Name, "null", args)};");
            }

            if (member.HasSetter)
            {
                sb.AppendLine($"            set => _adapter.SetProperty({getterId}, {id + 1}, \"set_{member.Name}\", {args}, value);");
            }

            sb.AppendLine("        }");
        }

        private static void EmitEvent(StringBuilder sb, MemberModel member, int id)
        {
            var field = "__event_" + id;
            var invokeArgs = string.Join(", ", member.Parameters.Select((p, i) => $"({p.Type})__raise[{i}]!"));
            var head = member.IsOverride ? $"public override event {member.ReturnType}? {member.Name}" : $"event {member.ReturnType}? {member.ContainingType}.{member.Name}";

            sb.AppendLine($"        private {member.ReturnType}? {field};");
            sb.AppendLine($"        {head}");
            sb.AppendLine("        {");
            sb.AppendLine("            add");
            sb.AppendLine("            {");
            sb.AppendLine($"                if (_adapter.EventAdd({id}, \"add_{member.Name}\", value, out var __raise))");
            sb.AppendLine($"                    {field}?.Invoke({invokeArgs});");
            sb.AppendLine("                else");
            sb.AppendLine($"                    {field} += value;");
            sb.AppendLine("            }");
            sb.AppendLine("            remove");
            sb.AppendLine("            {");
            sb.AppendLine($"                _adapter.EventRemove({id + 1}, \"remove_{member.Name}\", value);");
            sb.AppendLine($"                {field} -= value;");
            sb.AppendLine("            }");
            sb.AppendLine("        }");
        }

        public static string EmitRegistry(ImmutableArray<(string Type, string MockName)> items)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("namespace Glue.Mocks.Generated");
            sb.AppendLine("{");
            sb.AppendLine("    internal static class GlueMocksRegistration");
            sb.AppendLine("    {");
            sb.AppendLine("        [global::System.Runtime.CompilerServices.ModuleInitializer]");
            sb.AppendLine("        internal static void Register()");
            sb.AppendLine("        {");

            foreach (var (type, mockName) in items)
            {
                sb.AppendLine($"            global::Glue.Mocks.MockRegistry.Register<{type}>(static () => new {mockName}());");
            }

            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            return sb.ToString();
        }

        public static string EmitInterceptors(ImmutableArray<InterceptModel> items, ImmutableArray<ArgInterceptModel> args)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("namespace System.Runtime.CompilerServices");
            sb.AppendLine("{");
            sb.AppendLine("    [global::System.AttributeUsage(global::System.AttributeTargets.Method, AllowMultiple = true)]");
            sb.AppendLine("    file sealed class InterceptsLocationAttribute : global::System.Attribute");
            sb.AppendLine("    {");
            sb.AppendLine("        public InterceptsLocationAttribute(int version, string data) { }");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            sb.AppendLine("namespace Glue.Mocks.Generated");
            sb.AppendLine("{");
            sb.AppendLine("    file static class SubstituteInterceptors");
            sb.AppendLine("    {");

            var index = 0;

            foreach (var group in items.GroupBy(i => (i.Type, i.MockName)).OrderBy(g => g.Key.Type, System.StringComparer.Ordinal))
            {
                foreach (var site in group)
                {
                    sb.AppendLine($"        [global::System.Runtime.CompilerServices.InterceptsLocation({site.Version}, \"{site.Data}\")]");
                }

                // Not generic: the signature is compared with the constructed Substitute.For<T>().
                sb.AppendLine($"        public static {group.Key.Type} For_{index++}() => new {group.Key.MockName}();");
            }

            foreach (var group in args.GroupBy(a => (a.Kind, a.Position)).OrderBy(g => g.Key.Kind).ThenBy(g => g.Key.Position))
            {
                foreach (var site in group)
                {
                    sb.AppendLine($"        [global::System.Runtime.CompilerServices.InterceptsLocation({site.Version}, \"{site.Data}\")]");
                }

                var position = group.Key.Position;

                sb.AppendLine(group.Key.Kind switch
                {
                    "Any" => $"        public static ref T Any_{position}<T>() => ref global::Glue.Mocks.Arg.AnyAt<T>({position});",
                    "IsPredicate" => $"        public static ref T IsPredicate_{position}<T>(global::System.Func<T, bool> predicate) => ref global::Glue.Mocks.Arg.IsAt<T>({position}, predicate);",
                    _ => $"        public static ref T IsValue_{position}<T>(T value) => ref global::Glue.Mocks.Arg.IsAt<T>({position}, value);",
                });
            }

            sb.AppendLine("    }");
            sb.AppendLine("}");
            return sb.ToString();
        }
    }
}
