using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Gen;

// Spike only. It reruns on every compilation change. A real generator needs an incremental pipeline.
[Generator(LanguageNames.CSharp)]
public sealed class VerifyGenerator : IIncrementalGenerator
{
    const string Suffix = "__Verified";

    static readonly SymbolDisplayFormat TypeFormat = SymbolDisplayFormat.FullyQualifiedFormat
        .AddMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

    public void Initialize(IncrementalGeneratorInitializationContext context) =>
        context.RegisterSourceOutput(context.CompilationProvider, Execute);

    static void Execute(SourceProductionContext spc, Compilation comp)
    {
        var __sw = System.Diagnostics.Stopwatch.StartNew(); long __t1 = 0, __t2 = 0, __symTicks = 0, __locTicks = 0;
        var verifyAttr = comp.GetTypeByMetadataName("VerifyGlue.VerifyAttribute");
        var verifySyntax = comp.GetTypeByMetadataName("VerifyGlue.VerifySyntax");
        if (verifyAttr is null || verifySyntax is null) return;

        bool IsVerifyCall(SemanticModel model, InvocationExpressionSyntax inv) =>
            model.GetSymbolInfo(inv).Symbol is IMethodSymbol { Name: "Verify" } m
            && SymbolEqualityComparer.Default.Equals(m.ContainingType, verifySyntax);

        // Pass 1: [Verify] methods that can be cloned.
        var cloned = new HashSet<ISymbol>(SymbolEqualityComparer.Default);
        var decls = new List<(MethodDeclarationSyntax Decl, IMethodSymbol Symbol, SemanticModel Model)>();
        foreach (var tree in comp.SyntaxTrees)
        {
            var model = comp.GetSemanticModel(tree);
            foreach (var decl in tree.GetRoot().DescendantNodes().OfType<MethodDeclarationSyntax>())
            {
                if (decl.Body is null || decl.AttributeLists.Count == 0) continue;
                if (model.GetDeclaredSymbol(decl) is not IMethodSymbol symbol) continue;
                if (!symbol.GetAttributes().Any(a => SymbolEqualityComparer.Default.Equals(a.AttributeClass, verifyAttr))) continue;
                var allPartial = decl.Ancestors().OfType<TypeDeclarationSyntax>()
                    .All(t => t.Modifiers.Any(SyntaxKind.PartialKeyword));
                if (!allPartial) continue;
                cloned.Add(symbol);
                decls.Add((decl, symbol, model));
            }
        }

        __t1 = __sw.ElapsedMilliseconds;
        // Pass 2: emit one clone per method with every Verify(...) statement rewritten.
        var site = 0;
        var fileIndex = 0;
        foreach (var (decl, symbol, model) in decls)
        {
            var src = EmitClone(decl, model, cloned, IsVerifyCall, ref site);
            spc.AddSource($"{symbol.ContainingType.Name}.{symbol.Name}.{fileIndex++}.Verified.g.cs", src);
        }

        __t2 = __sw.ElapsedMilliseconds;
        // Pass 3: interceptors.
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("#pragma warning disable");
        sb.AppendLine("namespace System.Runtime.CompilerServices { [global::System.AttributeUsage(global::System.AttributeTargets.Method, AllowMultiple = true)] file sealed class InterceptsLocationAttribute(int version, string data) : global::System.Attribute; }");
        sb.AppendLine("namespace VerifyGlue.Generated {");
        sb.AppendLine("static file class VerifyInterceptors {");
        var n = 0;
        foreach (var tree in comp.SyntaxTrees)
        {
            var model = comp.GetSemanticModel(tree);
            foreach (var inv in tree.GetRoot().DescendantNodes().OfType<InvocationExpressionSyntax>())
            {
                var __a = __sw.ElapsedTicks;
                var __sym = model.GetSymbolInfo(inv).Symbol;
                __symTicks += __sw.ElapsedTicks - __a;
                if (__sym is not IMethodSymbol target) continue;
                if (IsVerifyCall(model, inv) && inv.ArgumentList.Arguments.Count == 1)
                {
                    __a = __sw.ElapsedTicks;
                    var loc = model.GetInterceptableLocation(inv);
                    __locTicks += __sw.ElapsedTicks - __a;
                    if (loc is null) continue;
                    var arg = inv.ArgumentList.Arguments[0].Expression;
                    var pos = inv.GetLocation().GetLineSpan();
                    sb.AppendLine($"  {loc.GetInterceptsLocationAttributeSyntax()} // {loc.GetDisplayLocation()}");
                    sb.AppendLine($"  public static void Verify_{n++}([global::System.Diagnostics.CodeAnalysis.DoesNotReturnIf(false)] bool condition, string? expression = null, string file = \"\", int line = 0)");
                    sb.AppendLine($"  {{ if (!condition) throw new global::VerifyGlue.VerifyException({Lit(StaticMessage(arg) + "\n  at " + pos.Path + ":" + (pos.StartLinePosition.Line + 1) + " (interceptor, static message only)")}); }}");
                }
                else if (cloned.Contains(target) && !target.IsGenericMethod && !target.ContainingType.IsGenericType)
                {
                    var loc = model.GetInterceptableLocation(inv);
                    if (loc is null) continue;
                    var ps = new List<string>();
                    var args = new List<string>();
                    if (!target.IsStatic) ps.Add($"this {target.ContainingType.ToDisplayString(TypeFormat)} @this");
                    foreach (var p in target.Parameters)
                    {
                        var rk = p.RefKind switch { RefKind.Ref => "ref ", RefKind.Out => "out ", RefKind.In => "in ", _ => "" };
                        ps.Add($"{rk}{p.Type.ToDisplayString(TypeFormat)} {p.Name}");
                        args.Add(rk + p.Name);
                    }
                    var recv = target.IsStatic ? target.ContainingType.ToDisplayString(TypeFormat) : "@this";
                    sb.AppendLine($"  {loc.GetInterceptsLocationAttributeSyntax()} // {loc.GetDisplayLocation()}");
                    sb.AppendLine($"  public static {target.ReturnType.ToDisplayString(TypeFormat)} Redirect_{n++}({string.Join(", ", ps)}) => {recv}.{target.Name}{Suffix}({string.Join(", ", args)});");
                }
            }
        }
        sb.AppendLine("}}");
        sb.AppendLine($"// generator ms: pass1={__t1} pass2={__t2 - __t1} pass3={__sw.ElapsedMilliseconds - __t2} sym={__symTicks * 1000 / System.Diagnostics.Stopwatch.Frequency} loc={__locTicks * 1000 / System.Diagnostics.Stopwatch.Frequency}");
        spc.AddSource("VerifyInterceptors.g.cs", sb.ToString());
    }

    // What an interceptor alone can say: the argument syntax is known, the operand values are not.
    static string StaticMessage(ExpressionSyntax arg)
    {
        if (arg is IsPatternExpressionSyntax { Pattern: UnaryPatternSyntax { Pattern: ConstantPatternSyntax { Expression: LiteralExpressionSyntax l } } } ip
            && l.IsKind(SyntaxKind.NullLiteralExpression))
            return $"{ip.Expression} can not be null";
        if (arg is BinaryExpressionSyntax b && b.IsKind(SyntaxKind.EqualsExpression))
            return $"Verify failed: expected {b.Left} to equal {b.Right}";
        return $"Verify failed: {OneLine(arg)}";
    }

    static string EmitClone(MethodDeclarationSyntax decl, SemanticModel model, HashSet<ISymbol> cloned,
        System.Func<SemanticModel, InvocationExpressionSyntax, bool> isVerifyCall, ref int site)
    {
        var body = decl.Body!;
        var tree = decl.SyntaxTree;
        var text = tree.GetText();
        var path = tree.FilePath;

        // Splices against the original body text.
        var splices = new List<(int Start, int End, string Text)>();
        foreach (var stmt in body.DescendantNodes().OfType<ExpressionStatementSyntax>())
        {
            if (stmt.Expression is not InvocationExpressionSyntax inv) continue;
            if (!isVerifyCall(model, inv) || inv.ArgumentList.Arguments.Count != 1) continue;
            var rw = new Rewriter(model, site++);
            var arg = inv.ArgumentList.Arguments[0].Expression;
            var cond = rw.Rewrite(arg, null, top: true).Text;
            var line = stmt.GetLocation().GetLineSpan().StartLinePosition.Line + 1;
            var sb = new StringBuilder();
            foreach (var c in rw.Captures) sb.Append($"{c.Type} {c.Name} = default!; ");
            sb.Append($"if (!({cond})) {{ throw global::VerifyGlue.VerifyFailure.Create({Lit(OneLine(arg))}, {Lit(path)}, {line})");
            foreach (var c in rw.Captures.OrderBy(c => c.Start).ThenByDescending(c => c.Length))
            {
                sb.Append($".With({Lit(c.Text)}, {c.Name}{(c.Guard is null ? "" : ", " + c.Guard)})");
                foreach (var note in rw.Notes.Where(x => x.Capture == c.Name)) sb.Append(note.Code);
            }
            sb.Append(".Build(); }");
            var replacement = sb.ToString();
            if (stmt.Parent is not BlockSyntax) replacement = "{ " + replacement + " }";
            // Keep the line count so one #line directive covers the whole body.
            replacement += new string('\n', stmt.ToString().Count(ch => ch == '\n'));
            splices.Add((stmt.SpanStart, stmt.Span.End, replacement));
        }
        foreach (var inv in body.DescendantNodes().OfType<InvocationExpressionSyntax>())
        {
            if (model.GetSymbolInfo(inv).Symbol is not IMethodSymbol target || !cloned.Contains(target.OriginalDefinition)) continue;
            SimpleNameSyntax? name = inv.Expression switch
            {
                SimpleNameSyntax s => s,
                MemberAccessExpressionSyntax ma => ma.Name,
                _ => null,
            };
            if (name is null) continue;
            var tok = name.Identifier;
            if (splices.Any(s => s.Start <= tok.SpanStart && tok.Span.End <= s.End)) continue;
            splices.Add((tok.SpanStart, tok.Span.End, tok.ValueText + Suffix));
        }

        var bodyText = new StringBuilder();
        var cursor = body.SpanStart;
        foreach (var s in splices.OrderBy(s => s.Start))
        {
            bodyText.Append(text.ToString(Microsoft.CodeAnalysis.Text.TextSpan.FromBounds(cursor, s.Start)));
            bodyText.Append(s.Text);
            cursor = s.End;
        }
        bodyText.Append(text.ToString(Microsoft.CodeAnalysis.Text.TextSpan.FromBounds(cursor, body.Span.End)));

        var o = new StringBuilder();
        o.AppendLine("// <auto-generated/>");
        o.AppendLine("#pragma warning disable");
        if ((model.GetNullableContext(body.SpanStart) & NullableContext.AnnotationsEnabled) != 0) o.AppendLine("#nullable enable");
        var root = (CompilationUnitSyntax)tree.GetRoot();
        foreach (var u in root.Usings) o.AppendLine(u.ToString());
        var closers = 0;
        foreach (var anc in decl.Ancestors().Reverse())
        {
            switch (anc)
            {
                case BaseNamespaceDeclarationSyntax ns:
                    o.AppendLine($"namespace {ns.Name} {{");
                    foreach (var u in ns.Usings) o.AppendLine(u.ToString());
                    closers++;
                    break;
                case TypeDeclarationSyntax t:
                    o.AppendLine($"partial {t.Keyword.ValueText} {t.Identifier.ValueText}{t.TypeParameterList} {{");
                    closers++;
                    break;
            }
        }
        var mods = string.Join(" ", decl.Modifiers
            .Where(m => m.IsKind(SyntaxKind.StaticKeyword) || m.IsKind(SyntaxKind.AsyncKeyword) || m.IsKind(SyntaxKind.UnsafeKeyword))
            .Select(m => m.ValueText));
        o.AppendLine("[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
        o.AppendLine($"internal {mods} {decl.ReturnType} {decl.Identifier.ValueText}{Suffix}{decl.TypeParameterList}{decl.ParameterList} {string.Join(" ", decl.ConstraintClauses.Select(c => c.ToString()))}");
        var open = body.OpenBraceToken.GetLocation().GetLineSpan().StartLinePosition;
        o.AppendLine($"#line {open.Line + 1} {Lit(path)}");
        o.Append(new string(' ', open.Character)).AppendLine(bodyText.ToString());
        o.AppendLine("#line default");
        o.AppendLine(new string('}', closers));
        return o.ToString();
    }

    static string Lit(string s) => SymbolDisplay.FormatLiteral(s, quote: true);

    static string OneLine(SyntaxNode n) => string.Join(" ", n.ToString().Split(new[] { '\r', '\n' }, System.StringSplitOptions.RemoveEmptyEntries).Select(x => x.Trim()));

    sealed class Capture
    {
        public string Name = "", Type = "", Text = "";
        public string? Guard;
        public int Start, Length;
    }

    // Wraps each sub-expression in an assignment to a typed local: (tmp = expr).
    // The expression keeps its shape, so evaluation order and short-circuiting do not change
    // and every sub-expression still runs exactly once.
    sealed class Rewriter(SemanticModel model, int site)
    {
        public readonly List<Capture> Captures = new();
        public readonly List<(string Capture, string Code)> Notes = new();
        int _pattern;

        public (string Text, string? Cap) Rewrite(ExpressionSyntax e, string? guard, bool top = false)
        {
            if (e is ParenthesizedExpressionSyntax paren)
            {
                var r = Rewrite(paren.Expression, guard, top);
                return ("(" + r.Text + ")", r.Cap);
            }
            if (e is LiteralExpressionSyntax || model.GetConstantValue(e).HasValue) return (e.ToString(), null);

            string inner;
            switch (e)
            {
                case BinaryExpressionSyntax b when b.IsKind(SyntaxKind.LogicalAndExpression) || b.IsKind(SyntaxKind.LogicalOrExpression):
                {
                    var l = Rewrite(b.Left, guard);
                    var g = guard;
                    if (l.Cap is not null)
                    {
                        var mine = b.IsKind(SyntaxKind.LogicalAndExpression) ? l.Cap : "!" + l.Cap;
                        g = guard is null ? mine : guard + " && " + mine;
                    }
                    inner = l.Text + " " + b.OperatorToken.Text + " " + Rewrite(b.Right, g).Text;
                    break;
                }
                case BinaryExpressionSyntax b when b.IsKind(SyntaxKind.IsExpression) || b.IsKind(SyntaxKind.AsExpression):
                    inner = Rewrite(b.Left, guard).Text + " " + b.OperatorToken.Text + " " + b.Right;
                    break;
                case BinaryExpressionSyntax b when !b.IsKind(SyntaxKind.CoalesceExpression):
                    inner = Rewrite(b.Left, guard).Text + " " + b.OperatorToken.Text + " " + Rewrite(b.Right, guard).Text;
                    break;
                case PrefixUnaryExpressionSyntax u when u.IsKind(SyntaxKind.LogicalNotExpression):
                    inner = "!" + Rewrite(u.Operand, guard).Text;
                    break;
                case IsPatternExpressionSyntax ip:
                {
                    var operand = Rewrite(ip.Expression, guard);
                    inner = operand.Text + " is " + ip.Pattern;
                    if (operand.Cap is not null) AddPatternNotes(ip, operand.Cap);
                    break;
                }
                case MemberAccessExpressionSyntax ma when ma.IsKind(SyntaxKind.SimpleMemberAccessExpression):
                    inner = CanHoistReceiver(ma.Expression) ? Rewrite(ma.Expression, guard).Text + "." + ma.Name : e.ToString();
                    break;
                case InvocationExpressionSyntax inv:
                {
                    var callee = inv.Expression is MemberAccessExpressionSyntax ma && ma.IsKind(SyntaxKind.SimpleMemberAccessExpression) && CanHoistReceiver(ma.Expression)
                        ? Rewrite(ma.Expression, guard).Text + "." + ma.Name
                        : inv.Expression.ToString();
                    var args = inv.ArgumentList.Arguments.Select(a =>
                        a.RefKindKeyword.IsKind(SyntaxKind.None) ? a.NameColon + Rewrite(a.Expression, guard).Text : a.ToString());
                    inner = callee + "(" + string.Join(", ", args) + ")";
                    break;
                }
                default:
                    inner = e.ToString();
                    break;
            }
            return top ? (inner, null) : TryCapture(e, inner, guard);
        }

        bool CanHoistReceiver(ExpressionSyntax receiver)
        {
            if (model.GetSymbolInfo(receiver).Symbol is INamespaceSymbol or ITypeSymbol) return false;
            var t = model.GetTypeInfo(receiver).Type;
            // Copying a mutable struct into a local would send a mutating call to the copy.
            return t is not null && (!t.IsValueType || t.IsReadOnly);
        }

        (string, string?) TryCapture(ExpressionSyntax e, string inner, string? guard)
        {
            var t = model.GetTypeInfo(e).Type;
            if (t is null || t.SpecialType == SpecialType.System_Void || t.IsAnonymousType || t.IsRefLikeType
                || t.TypeKind is TypeKind.Error or TypeKind.Pointer or TypeKind.FunctionPointer or TypeKind.Dynamic)
                return (inner, null);
            if (e is InterpolatedStringExpressionSyntax or TupleExpressionSyntax or LambdaExpressionSyntax or BaseExpressionSyntax) return (inner, null);
            if (e is IdentifierNameSyntax && model.GetSymbolInfo(e).Symbol is not (ILocalSymbol or IParameterSymbol or IFieldSymbol or IPropertySymbol))
                return (inner, null);
            var c = new Capture
            {
                Name = $"__v{site}_{Captures.Count}",
                Type = t.ToDisplayString(TypeFormat),
                Text = OneLine(e),
                Guard = guard,
                Start = e.SpanStart,
                Length = e.Span.Length,
            };
            Captures.Add(c);
            return ($"({c.Name} = {inner})", c.Name);
        }

        // Runs only on the failure path, against the captured operand.
        void AddPatternNotes(IsPatternExpressionSyntax ip, string cap)
        {
            if (ip.Pattern is not RecursivePatternSyntax { PropertyPatternClause: { } props } rp) return;
            foreach (var sub in props.Subpatterns)
            {
                if (sub.NameColon is null) continue;
                var member = sub.NameColon.Name.Identifier.ValueText;
                var p = $"__p{site}_{_pattern++}";
                Notes.Add((cap,
                    $".Member({Lit(OneLine(ip.Expression) + "." + member)}, " +
                    $"{cap} is {rp.Type} {{ {member}: var {p} }} ? global::VerifyGlue.VerifyFormat.Format({p}) : \"<unavailable>\", " +
                    $"{Lit(OneLine(sub.Pattern))}, {cap} is {rp.Type} {{ {sub} }})"));
            }
        }
    }
}
