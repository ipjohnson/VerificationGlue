using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.IO;
using System.Linq;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace ClosureGlue.Gen;

/// <summary>One intercepted <c>Verify(() =&gt; ...)</c> call.</summary>
internal sealed record Site(
    string FilePath,
    int Line,
    int Version,
    string Data,
    string Text,
    string? Namespace,
    string Usings,
    string? Explain,
    string? Reason,
    bool Single);

[Generator]
public sealed class ClosureGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var sites = context.SyntaxProvider.CreateSyntaxProvider(
                static (node, _) => node is InvocationExpressionSyntax { ArgumentList.Arguments.Count: 1 } invocation &&
                    invocation.ArgumentList.Arguments[0].Expression is ParenthesizedLambdaExpressionSyntax &&
                    invocation.Expression is IdentifierNameSyntax { Identifier.ValueText: "Verify" } or MemberAccessExpressionSyntax { Name.Identifier.ValueText: "Verify" },
                static (syntax, token) => syntax)
            .Combine(context.AnalyzerConfigOptionsProvider.Select(static (options, _) =>
                !(options.GlobalOptions.TryGetValue("build_property.ClosureGlueMode", out var mode) && mode == "rerun")))
            .Select(static (pair, token) => Build(pair.Left, pair.Right, token))
            .Where(static site => site is not null)
            .Select(static (site, _) => site!);

        context.RegisterSourceOutput(sites.Collect(), static (output, all) =>
        {
            var index = 0;
            foreach (var file in all.GroupBy(site => site.FilePath))
            {
                output.AddSource(Path.GetFileNameWithoutExtension(file.Key) + "." + index + ".Closure.g.cs", Emit(file.ToList(), ref index));
            }
        });
    }

    private static Site? Build(GeneratorSyntaxContext syntax, bool single, CancellationToken token)
    {
        var invocation = (InvocationExpressionSyntax)syntax.Node;
        var model = syntax.SemanticModel;
        if (model.GetSymbolInfo(invocation, token).Symbol is not IMethodSymbol method ||
            method.ContainingType.ToDisplayString() != "ClosureGlue.Checks" ||
            method.Parameters[0].Type.Name != "Func" ||
            model.GetInterceptableLocation(invocation, token) is not { } location)
        {
            return null;
        }

        var lambda = (ParenthesizedLambdaExpressionSyntax)invocation.ArgumentList.Arguments[0].Expression;
        var line = invocation.GetLocation().GetLineSpan().StartLinePosition.Line + 1;
        var text = Normalize(lambda.ToString());
        var containingType = model.GetEnclosingSymbol(invocation.SpanStart, token)?.ContainingType;
        var ns = containingType?.ContainingNamespace is { IsGlobalNamespace: false } containingNamespace ? containingNamespace.ToDisplayString() : null;
        var usings = Usings(invocation);

        string? explain = null;
        string? reason = null;
        try
        {
            explain = new Instrumenter(model, lambda, containingType, single, token).Run();
        }
        catch (UnsupportedException unsupported)
        {
            reason = unsupported.Message;
        }

        return new Site(invocation.SyntaxTree.FilePath, line, location.Version, location.Data, text, ns, usings, explain, reason, single);
    }

    private static string Usings(SyntaxNode node)
    {
        var text = new StringBuilder();
        foreach (var scope in node.Ancestors())
        {
            var directives = scope switch
            {
                CompilationUnitSyntax unit => unit.Usings,
                BaseNamespaceDeclarationSyntax declaration => declaration.Usings,
                _ => default,
            };

            foreach (var directive in directives.Where(directive => directive.GlobalKeyword.IsKind(SyntaxKind.None)))
            {
                text.Append(directive.ToString()).Append('\n');
            }
        }

        return text.ToString();
    }

    internal static string Normalize(string text) => string.Join(" ", text.Split(new[] { ' ', '\r', '\n', '\t' }, StringSplitOptions.RemoveEmptyEntries));

    private static string Emit(List<Site> sites, ref int index)
    {
        var text = new StringBuilder("// <auto-generated/>\n#nullable disable\n#pragma warning disable\n");
        text.Append(sites[0].Usings);
        text.Append("namespace System.Runtime.CompilerServices\n{\n" +
            "    [global::System.AttributeUsage(global::System.AttributeTargets.Method, AllowMultiple = true)]\n" +
            "    file sealed class InterceptsLocationAttribute(int version, string data) : global::System.Attribute\n    {\n    }\n}\n");

        var explainers = new StringBuilder();
        text.Append("namespace ClosureGlue.Generated\n{\n    file static class ClosureInterceptors\n    {\n");
        foreach (var site in sites)
        {
            var id = index++;
            var where = Path.GetFileName(site.FilePath) + ":" + site.Line;
            text.Append("        [global::System.Runtime.CompilerServices.InterceptsLocation(").Append(site.Version).Append(", \"").Append(site.Data).Append("\")]\n")
                .Append("        public static void Verify").Append(id).Append("(global::System.Func<bool> condition, string text)\n        {\n");
            var explainer = (site.Namespace is null ? "global::" : "global::" + site.Namespace + ".") + "ClosureExplain" + id;
            if (site.Single && site.Explain is not null)
            {
                // The copy is the only evaluation. It returns null when it cannot read the closure, and the delegate runs instead.
                text.Append("            switch (").Append(explainer).Append(".Check(condition.Target, \"").Append(Escape(where)).Append("\", out var reason))\n            {\n")
                    .Append("                case true:\n                    return;\n")
                    .Append("                case null when condition():\n                    return;\n")
                    .Append("                default:\n                    throw new global::ClosureGlue.VerifyException(\"Verify failed: ").Append(Escape(site.Text))
                    .Append("\\n  values not captured: \" + reason + \"\\n  at ").Append(where).Append("\");\n")
                    .Append("            }\n        }\n\n");
                AppendExplainer(explainers, site, id);
                continue;
            }

            text.Append("            if (condition())\n            {\n                return;\n            }\n\n");
            if (site.Explain is null)
            {
                text.Append("            throw new global::ClosureGlue.VerifyException(\"Verify failed: ").Append(Escape(site.Text))
                    .Append("\\n  values not captured: ").Append(Escape(site.Reason!)).Append("\\n  at ").Append(where).Append("\");\n        }\n\n");
                continue;
            }

            text.Append("            string values;\n            try\n            {\n")
                .Append("                values = ").Append(explainer).Append(".Run(condition.Target);\n")
                .Append("            }\n            catch (global::System.Exception exception)\n            {\n")
                .Append("                values = \"  values not captured: \" + exception.GetType().Name + \": \" + exception.Message + \"\\n\";\n")
                .Append("            }\n\n")
                .Append("            throw new global::ClosureGlue.VerifyException(\"Verify failed: ").Append(Escape(site.Text)).Append("\\n\" + values + \"  at ").Append(where).Append("\");\n")
                .Append("        }\n\n");

            AppendExplainer(explainers, site, id);
        }

        text.Append("    }\n}\n");
        text.Append(explainers);
        return text.ToString();
    }

    private static void AppendExplainer(StringBuilder explainers, Site site, int id) =>
        explainers.Append(site.Namespace is null ? "" : "namespace " + site.Namespace + "\n{\n")
            .Append("    file static class ClosureExplain").Append(id).Append("\n    {\n")
            .Append(site.Explain)
            .Append("    }\n")
            .Append(site.Namespace is null ? "" : "}\n");

    private static string Escape(string text) => text.Replace("\\", "\\\\").Replace("\"", "\\\"");
}

internal sealed class UnsupportedException(string message) : Exception(message);

/// <summary>
/// Copies the lambda's body into a static method. Each captured variable becomes a local of the same
/// name that is read from the closure, <c>this</c> becomes <c>__this</c>, an inaccessible member goes
/// through an <c>UnsafeAccessor</c>, and each part of the condition is wrapped in <c>__e.R(slot, ...)</c>.
/// </summary>
internal sealed class Instrumenter(SemanticModel model, ParenthesizedLambdaExpressionSyntax lambda, INamedTypeSymbol? containingType, bool single, CancellationToken token)
    : CSharpSyntaxRewriter
{
    private static readonly SymbolDisplayFormat Qualified = SymbolDisplayFormat.FullyQualifiedFormat;

    private readonly List<string> _texts = new();
    private readonly List<string?> _slotTypes = new();
    private readonly Dictionary<string, ISymbol> _captured = new();
    private readonly List<string> _accessors = new();
    private readonly Dictionary<ISymbol, string> _accessorNames = new(SymbolEqualityComparer.Default);
    private bool _usesThis;
    private int _nestedLambdas;

    public string Run()
    {
        if (lambda.ExpressionBody is not { } body)
        {
            throw new UnsupportedException("the lambda has a block body");
        }

        // The copy works on locals, so a write would not reach the closure.
        var flow = model.AnalyzeDataFlow(body);
        if (flow is { Succeeded: true } && flow.WrittenInside.FirstOrDefault(symbol => !lambda.Span.Contains(symbol.DeclaringSyntaxReferences.FirstOrDefault()?.Span ?? default)) is { } written)
        {
            throw new UnsupportedException("the condition writes " + written.Name);
        }

        var rewritten = Visit(body)!.ToString();
        if (single)
        {
            return Single(rewritten);
        }

        var text = new StringBuilder();
        foreach (var accessor in _accessors)
        {
            text.Append(accessor);
        }

        if (containingType is not null && Nameable(containingType))
        {
            // Display classes are nested types of the containing type. Keeping all of its members keeps their fields under trimming.
            text.Append("        [global::System.Diagnostics.CodeAnalysis.DynamicDependency(global::System.Diagnostics.CodeAnalysis.DynamicallyAccessedMemberTypes.All, typeof(")
                .Append(containingType.ToDisplayString(Qualified)).Append("))]\n");
        }

        text.Append("        public static string Run(object __target)\n        {\n");
        if (_usesThis)
        {
            text.Append("            var __this = global::ClosureGlue.Closure.This<").Append(Name(containingType!, "the containing type")).Append(">(__target);\n");
        }

        foreach (var pair in _captured)
        {
            switch (pair.Value)
            {
                case ILocalSymbol { IsConst: true } constant:
                    text.Append("            const ").Append(Name(constant.Type, pair.Key)).Append(' ').Append(pair.Key).Append(" = ")
                        .Append(SymbolDisplay.FormatPrimitive(constant.ConstantValue!, quoteStrings: true, useHexadecimalNumbers: false)).Append(";\n");
                    break;
                case IParameterSymbol parameter when IsPrimaryConstructorParameter(parameter):
                    text.Append("            var ").Append(pair.Key).Append(" = global::ClosureGlue.Closure.Read<").Append(Name(parameter.Type, pair.Key))
                        .Append(">(global::ClosureGlue.Closure.This<").Append(Name(containingType!, "the containing type")).Append(">(__target), \"<").Append(pair.Key).Append(">P\");\n");
                    break;
                default:
                    var type = pair.Value is ILocalSymbol local ? local.Type : ((IParameterSymbol)pair.Value).Type;
                    text.Append("            var ").Append(pair.Key).Append(" = global::ClosureGlue.Closure.Read<").Append(Name(type, pair.Key))
                        .Append(">(__target, \"").Append(pair.Key).Append("\");\n");
                    break;
            }
        }

        text.Append("            var __e = new global::ClosureGlue.Explanation(new string[] { ")
            .Append(string.Join(", ", _texts.Select(t => SymbolDisplay.FormatLiteral(t, quote: true)))).Append(" });\n")
            .Append("            _ = ").Append(rewritten).Append(";\n")
            .Append("            return __e.Render();\n        }\n");
        return text.ToString();
    }

    public override SyntaxNode? Visit(SyntaxNode? node)
    {
        if (node is not ExpressionSyntax expression || !ShouldRecord(expression))
        {
            return base.Visit(node);
        }

        string? slotType = null;
        if (single)
        {
            // A typed local holds the part, so a part whose type cannot be named is not shown.
            var type = model.GetTypeInfo(expression, token).Type!;
            if (!Nameable(type))
            {
                return base.Visit(node);
            }

            slotType = type.ToDisplayString(Qualified);
        }

        var slot = _texts.Count;
        _texts.Add(ClosureGenerator.Normalize(expression.ToString()));
        _slotTypes.Add(slotType);
        var rewritten = ((ExpressionSyntax)base.Visit(node)!).ToFullString().Trim();
        return SyntaxFactory.ParseExpression(single
            ? "global::ClosureGlue.Slot.R(ref __v" + slot + ", ref __s" + slot + ", " + rewritten + ")"
            : "__e.R(" + slot + ", " + rewritten + ")");
    }

    /// <summary>
    /// The single-evaluation copy. It reads each capture through a cached <c>Capture</c>, runs the
    /// instrumented condition once with each part in a typed local, and builds the message only on failure.
    /// It returns null when a capture cannot be read, before any part of the condition has run.
    /// </summary>
    private string Single(string rewritten)
    {
        var text = new StringBuilder();
        foreach (var accessor in _accessors)
        {
            text.Append(accessor);
        }

        var containing = _usesThis || _captured.Values.OfType<IParameterSymbol>().Any(IsPrimaryConstructorParameter) ? Name(containingType!, "the containing type") : null;
        if (containing is not null)
        {
            text.Append("        private static readonly global::ClosureGlue.Capture __cthis = new(\"<>4__this\");\n");
        }

        var reads = new StringBuilder();
        var declarations = new StringBuilder();
        if (containing is not null)
        {
            declarations.Append("            ").Append(containing).Append(" __this;\n");
            reads.Append("                __this = __cthis.This<").Append(containing).Append(">(__target);\n");
        }

        var index = 0;
        foreach (var pair in _captured)
        {
            if (pair.Value is ILocalSymbol { IsConst: true } constant)
            {
                declarations.Append("            const ").Append(Name(constant.Type, pair.Key)).Append(' ').Append(pair.Key).Append(" = ")
                    .Append(SymbolDisplay.FormatPrimitive(constant.ConstantValue!, quoteStrings: true, useHexadecimalNumbers: false)).Append(";\n");
                continue;
            }

            var primary = pair.Value is IParameterSymbol parameter && IsPrimaryConstructorParameter(parameter);
            var type = Name(pair.Value is ILocalSymbol local ? local.Type : ((IParameterSymbol)pair.Value).Type, pair.Key);
            var field = primary ? "<" + pair.Key + ">P" : pair.Key;
            text.Append("        private static readonly global::ClosureGlue.Capture __c").Append(index).Append(" = new(\"").Append(field).Append("\");\n");
            declarations.Append("            ").Append(type).Append(' ').Append(pair.Key).Append(";\n");
            reads.Append("                ").Append(pair.Key).Append(" = __c").Append(index).Append(".Read<").Append(type).Append(">(").Append(primary ? "__this" : "__target").Append(");\n");
            index++;
        }

        if (containingType is not null && Nameable(containingType))
        {
            text.Append("        [global::System.Diagnostics.CodeAnalysis.DynamicDependency(global::System.Diagnostics.CodeAnalysis.DynamicallyAccessedMemberTypes.All, typeof(")
                .Append(containingType.ToDisplayString(Qualified)).Append("))]\n");
        }

        text.Append("        public static bool? Check(object __target, string where, out string reason)\n        {\n")
            .Append(declarations)
            .Append("            try\n            {\n").Append(reads).Append("            }\n")
            .Append("            catch (global::System.Exception exception)\n            {\n")
            .Append("                reason = exception.GetType().Name + \": \" + exception.Message;\n                return null;\n            }\n\n")
            .Append("            reason = null;\n");
        for (var slot = 0; slot < _texts.Count; slot++)
        {
            text.Append("            ").Append(_slotTypes[slot]).Append(" __v").Append(slot).Append(" = default; bool __s").Append(slot).Append(" = false;\n");
        }

        text.Append("            if (").Append(rewritten).Append(")\n            {\n                return true;\n            }\n\n")
            .Append("            throw new global::ClosureGlue.FailureMessage(").Append(SymbolDisplay.FormatLiteral(ClosureGenerator.Normalize(lambda.ToString()), quote: true)).Append(", where)");
        for (var slot = 0; slot < _texts.Count; slot++)
        {
            text.Append("\n                .Add(").Append(SymbolDisplay.FormatLiteral(_texts[slot], quote: true)).Append(", __s").Append(slot).Append(", __v").Append(slot).Append(')');
        }

        text.Append("\n                .Build();\n        }\n");
        return text.ToString();
    }

    public override SyntaxNode? VisitParenthesizedLambdaExpression(ParenthesizedLambdaExpressionSyntax node) => Nested(() => base.VisitParenthesizedLambdaExpression(node));

    public override SyntaxNode? VisitSimpleLambdaExpression(SimpleLambdaExpressionSyntax node) => Nested(() => base.VisitSimpleLambdaExpression(node));

    public override SyntaxNode? VisitAnonymousMethodExpression(AnonymousMethodExpressionSyntax node) => Nested(() => base.VisitAnonymousMethodExpression(node));

    public override SyntaxNode? VisitThisExpression(ThisExpressionSyntax node)
    {
        _usesThis = true;
        return SyntaxFactory.IdentifierName("__this").WithTriviaFrom(node);
    }

    public override SyntaxNode? VisitBaseExpression(BaseExpressionSyntax node) => throw new UnsupportedException("the condition uses base");

    public override SyntaxNode? VisitMemberAccessExpression(MemberAccessExpressionSyntax node)
    {
        if (model.GetSymbolInfo(node, token).Symbol is { } member && !IsType(member) && !Accessible(member) && node.Parent is not InvocationExpressionSyntax)
        {
            var receiver = (ExpressionSyntax)Visit(node.Expression)!;
            return Parse(Accessor(member) + "(" + receiver + ")");
        }

        return base.VisitMemberAccessExpression(node);
    }

    public override SyntaxNode? VisitInvocationExpression(InvocationExpressionSyntax node)
    {
        if (model.GetSymbolInfo(node, token).Symbol is IMethodSymbol { MethodKind: MethodKind.LocalFunction })
        {
            throw new UnsupportedException("the condition calls a local function");
        }

        if (model.GetSymbolInfo(node, token).Symbol is IMethodSymbol target && !Accessible(target))
        {
            var receiver = node.Expression switch
            {
                MemberAccessExpressionSyntax access => ((ExpressionSyntax)Visit(access.Expression)!).ToString(),
                _ when target.IsStatic => "null",
                _ => This(),
            };
            var arguments = node.ArgumentList.Arguments.Select(argument => ((ExpressionSyntax)Visit(argument.Expression)!).ToString());
            return Parse(Accessor(target) + "(" + string.Join(", ", new[] { receiver }.Concat(arguments)) + ")");
        }

        return base.VisitInvocationExpression(node);
    }

    public override SyntaxNode? VisitIdentifierName(IdentifierNameSyntax node) => Simple(node) ?? base.VisitIdentifierName(node);

    public override SyntaxNode? VisitGenericName(GenericNameSyntax node) => Simple(node) ?? base.VisitGenericName(node);

    private SyntaxNode? Nested(Func<SyntaxNode?> visit)
    {
        _nestedLambdas++;
        try
        {
            return visit();
        }
        finally
        {
            _nestedLambdas--;
        }
    }

    /// <summary>Rewrites a simple name that is not the right side of a member access.</summary>
    private SyntaxNode? Simple(SimpleNameSyntax node)
    {
        if (node.Parent is MemberAccessExpressionSyntax access && access.Name == node ||
            node.Parent is MemberBindingExpressionSyntax ||
            node.Parent is NameColonSyntax ||
            node.Parent is QualifiedNameSyntax qualified && qualified.Right == node)
        {
            return null;
        }

        var info = model.GetSymbolInfo(node, token);
        var symbol = info.Symbol ?? info.CandidateSymbols.FirstOrDefault();
        switch (symbol)
        {
            case ILocalSymbol or IParameterSymbol when !lambda.Span.Contains(symbol.DeclaringSyntaxReferences.FirstOrDefault()?.Span ?? default):
                _captured[symbol.Name] = symbol;
                return null;
            case IMethodSymbol { MethodKind: MethodKind.LocalFunction }:
                throw new UnsupportedException("the condition calls a local function");
            case INamedTypeSymbol type when node is IdentifierNameSyntax:
                return Parse(Name(type, type.Name)).WithTriviaFrom(node);
            case IFieldSymbol or IPropertySymbol or IMethodSymbol or IEventSymbol when node.Parent is not MemberAccessExpressionSyntax || ((MemberAccessExpressionSyntax)node.Parent).Expression == node:
                if (node.Parent is InvocationExpressionSyntax && !Accessible(symbol))
                {
                    // VisitInvocationExpression handles the call.
                    return null;
                }

                if (!Accessible(symbol))
                {
                    return Parse(Accessor(symbol) + "(" + (symbol.IsStatic ? "null" : This()) + ")");
                }

                var prefix = symbol.IsStatic ? Name(symbol.ContainingType, symbol.ContainingType.Name) : This();
                return Parse(prefix + "." + node.ToString()).WithTriviaFrom(node);
            default:
                return null;
        }
    }

    private string This()
    {
        _usesThis = true;
        return "__this";
    }

    private bool ShouldRecord(ExpressionSyntax expression)
    {
        if (_nestedLambdas > 0 ||
            expression is LiteralExpressionSyntax or ParenthesizedExpressionSyntax or LambdaExpressionSyntax or AnonymousMethodExpressionSyntax or
                ThisExpressionSyntax or BaseExpressionSyntax or DefaultExpressionSyntax or InterpolatedStringExpressionSyntax or
                TypeSyntax and not IdentifierNameSyntax and not GenericNameSyntax or
                MemberBindingExpressionSyntax or ElementBindingExpressionSyntax or AssignmentExpressionSyntax or
                ImplicitObjectCreationExpressionSyntax or CollectionExpressionSyntax ||
            expression.Parent is MemberAccessExpressionSyntax { Name: var name } && name == expression ||
            expression.Parent is InvocationExpressionSyntax invocation && invocation.Expression == expression ||
            expression.Parent is ArgumentSyntax { RefKindKeyword.RawKind: not 0 } ||
            expression.Parent is NameColonSyntax or NameEqualsSyntax or AssignmentExpressionSyntax or MemberBindingExpressionSyntax or QualifiedNameSyntax or AliasQualifiedNameSyntax ||
            LeftmostIsBinding(expression) ||
            expression.Ancestors().TakeWhile(ancestor => ancestor != lambda).Any(ancestor => ancestor is PatternSyntax ||
                ancestor is InvocationExpressionSyntax { Expression: IdentifierNameSyntax { Identifier.ValueText: "nameof" } }))
        {
            return false;
        }

        var symbol = model.GetSymbolInfo(expression, token).Symbol;
        if (symbol is ITypeSymbol or INamespaceSymbol ||
            symbol is IMethodSymbol && expression is SimpleNameSyntax or MemberAccessExpressionSyntax)
        {
            return false;
        }

        var type = model.GetTypeInfo(expression, token).Type;
        if (type is null or IErrorTypeSymbol || type.SpecialType == SpecialType.System_Void || type.IsRefLikeType ||
            type.TypeKind is TypeKind.Pointer or TypeKind.FunctionPointer or TypeKind.Dynamic)
        {
            return false;
        }

        // A method call on a struct receiver would run on the copy that R returns.
        if (type.IsValueType && expression.Parent is MemberAccessExpressionSyntax receiverOf && receiverOf.Expression == expression &&
            receiverOf.Parent is InvocationExpressionSyntax)
        {
            return false;
        }

        return true;
    }

    private static bool LeftmostIsBinding(ExpressionSyntax expression)
    {
        while (true)
        {
            switch (expression)
            {
                case MemberBindingExpressionSyntax or ElementBindingExpressionSyntax:
                    return true;
                case MemberAccessExpressionSyntax access:
                    expression = access.Expression;
                    break;
                case InvocationExpressionSyntax invocation:
                    expression = invocation.Expression;
                    break;
                case ElementAccessExpressionSyntax element:
                    expression = element.Expression;
                    break;
                default:
                    return false;
            }
        }
    }

    private static bool IsType(ISymbol symbol) => symbol is ITypeSymbol or INamespaceSymbol;

    private bool Accessible(ISymbol symbol) => model.Compilation.IsSymbolAccessibleWithin(symbol, model.Compilation.Assembly);

    private static bool IsPrimaryConstructorParameter(IParameterSymbol parameter) =>
        parameter.DeclaringSyntaxReferences.FirstOrDefault()?.GetSyntax() is ParameterSyntax { Parent.Parent: TypeDeclarationSyntax };

    /// <summary>Declares an <c>UnsafeAccessor</c> for an inaccessible field, property or method.</summary>
    private string Accessor(ISymbol member)
    {
        if (_accessorNames.TryGetValue(member, out var existing))
        {
            return existing;
        }

        var name = "__Access" + _accessorNames.Count;
        _accessorNames[member] = name;
        var owner = Name(member.ContainingType, member.ContainingType.Name);
        var text = member switch
        {
            IFieldSymbol field =>
                $"        [global::System.Runtime.CompilerServices.UnsafeAccessor(global::System.Runtime.CompilerServices.UnsafeAccessorKind.{(field.IsStatic ? "StaticField" : "Field")}, Name = \"{field.Name}\")]\n" +
                $"        private static extern ref {Name(field.Type, field.Name)} {name}({owner} self);\n",
            IPropertySymbol { GetMethod: { } getter } property when !property.IsIndexer =>
                $"        [global::System.Runtime.CompilerServices.UnsafeAccessor(global::System.Runtime.CompilerServices.UnsafeAccessorKind.{(property.IsStatic ? "StaticMethod" : "Method")}, Name = \"{getter.Name}\")]\n" +
                $"        private static extern {Name(property.Type, property.Name)} {name}({owner} self);\n",
            IMethodSymbol { IsGenericMethod: false, ReturnsVoid: false } method when method.Parameters.All(parameter => parameter.RefKind == RefKind.None) =>
                $"        [global::System.Runtime.CompilerServices.UnsafeAccessor(global::System.Runtime.CompilerServices.UnsafeAccessorKind.{(method.IsStatic ? "StaticMethod" : "Method")}, Name = \"{method.Name}\")]\n" +
                $"        private static extern {Name(method.ReturnType, method.Name)} {name}({owner} self" +
                string.Concat(method.Parameters.Select(parameter => ", " + Name(parameter.Type, parameter.Name) + " " + parameter.Name)) + ");\n",
            _ => throw new UnsupportedException(member.Name + " is not accessible and is not a field, property or ordinary method"),
        };
        _accessors.Add(text);
        return name;
    }

    /// <summary>The type's name as generated code outside the containing type can write it.</summary>
    private string Name(ITypeSymbol type, string what)
    {
        if (!Nameable(type))
        {
            throw new UnsupportedException("the type of " + what + " cannot be named outside the test");
        }

        return type.ToDisplayString(Qualified);
    }

    private bool Nameable(ITypeSymbol type) => type switch
    {
        ITypeParameterSymbol => false,
        IArrayTypeSymbol array => Nameable(array.ElementType),
        IPointerTypeSymbol or IFunctionPointerTypeSymbol or IErrorTypeSymbol => false,
        INamedTypeSymbol { IsAnonymousType: true } => false,
        INamedTypeSymbol named => Accessible(named) && named.TypeArguments.All(Nameable),
        _ => true,
    };

    private static ExpressionSyntax Parse(string text) => SyntaxFactory.ParseExpression(text);
}
