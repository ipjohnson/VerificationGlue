using Microsoft.CodeAnalysis;
using VerificationGlue.Mocks.Generator;

namespace VerificationGlue.Tests.Generator.Specs;

/// <summary>
/// A test whose parameter, <c>[Mock]</c> parameter or constructor parameter type comes from an assembly
/// referenced through an extern alias. The registration declares the alias and writes <c>First::Vendor.Name</c>.
/// </summary>
public class ExternAliasSpecs
{
    private const string Vendor = """
        namespace Vendor
        {
            public enum Level { Low, High }

            public interface IClock { int Now(); }

            public interface IGateway { int Charge(Level level); }
        }
        """;

    private const string Tests = """
        extern alias First;
        using VerificationGlue.Mocks;
        using VerificationGlue.Tests;
        using static VerificationGlue.VerifySyntax;

        namespace Shop
        {
            public partial class GatewayTests([Mock] First::Vendor.IClock clock)
            {
                public static IEnumerable<First::Vendor.Level> Levels => [First::Vendor.Level.Low, First::Vendor.Level.High];

                [VerifyTest]
                public void Charges([Mock] First::Vendor.IGateway gateway, First::Vendor.Level level = First::Vendor.Level.High)
                {
                    clock.Now().Returns(3);
                    var now = clock.Now();
                    gateway.Charge(First::Vendor.Level.High).Returns(now);
                    Verify(gateway.Charge(level) == 3);
                }

                [VerifyTest]
                [RowSource(nameof(Levels))]
                public void Each(First::Vendor.Level level, [Mock] First::Vendor.IGateway gateway)
                {
                    gateway.Charge(level).Returns(1);
                    Verify(gateway.Charge(level) == 1);
                }
            }
        }
        """;

    [VerifyTest]
    public async Task A_test_with_parameters_from_an_extern_aliased_assembly_compiles_and_runs()
    {
        var tests = Registrations.Load(Tests, rewrite: false, [Library.Compile("Vendor", Vendor, "First")], new MockGenerator(), new TestGenerator());

        Assert.Equal(
            ["Shop.GatewayTests.Charges(Vendor.IGateway,Vendor.Level)", "Shop.GatewayTests.Each(Vendor.Level,Vendor.IGateway)#row(Vendor.Level:0)", "Shop.GatewayTests.Each(Vendor.Level,Vendor.IGateway)#row(Vendor.Level:1)"],
            tests.Keys.Order(StringComparer.Ordinal));
        foreach (var test in tests.Values)
        {
            Assert.Empty(await test());
        }
    }

    [VerifyTest]
    public void The_registration_declares_the_alias_and_writes_the_types_with_it(CancellationToken cancellationToken)
    {
        var input = GeneratorHarness.Compilation([("/repo/Tests/GatewayTests.cs", Tests)], Library.Compile("Vendor", Vendor, "First").Reference);

        GeneratorHarness.Driver(rewrite: false, new MockGenerator(), new TestGenerator()).RunGeneratorsAndUpdateCompilation(input, out var output, out _, cancellationToken);

        Assert.Empty(output.GetDiagnostics(cancellationToken).Where(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error));
        var registration = output.SyntaxTrees.Single(tree => tree.FilePath.EndsWith("Shop.GatewayTests.Tests.g.cs", StringComparison.Ordinal)).ToString();
        Assert.StartsWith("// <auto-generated/>\n#nullable enable\n#pragma warning disable\nextern alias First;\nnamespace ", registration, StringComparison.Ordinal);
        Assert.Contains("typeof(First::Vendor.IClock)", registration);
        Assert.Contains("Mock.Of<First::Vendor.IGateway>()", registration);
        Assert.Contains("(object?)(First::Vendor.Level)((First::Vendor.Level)(1))", registration);
        Assert.Contains("Member<First::Vendor.Level>(", registration);
        Assert.DoesNotContain("global::Vendor.", registration);
    }
}
