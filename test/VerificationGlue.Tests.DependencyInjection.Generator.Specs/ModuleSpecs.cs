using System.Reflection;
using System.Runtime.CompilerServices;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.Extensions.DependencyInjection;
using VerificationGlue.Tests.Generator;

namespace VerificationGlue.Tests.DependencyInjection.Generator.Specs;

/// <summary>
/// The source that adds the DependencyModules modules of a container's attributes. The modules here are
/// written by hand against the real DependencyModules.Runtime, so the specs need no DependencyModules generator.
/// </summary>
public class ModuleSpecs
{
    private const string Modules = """
        namespace Shop
        {
            public sealed record Entry(string Name);

            public sealed class NamedModule(string name) : DependencyModules.Runtime.Interfaces.IDependencyModule, DependencyModules.Runtime.Interfaces.IServiceCollectionConfiguration
            {
                public void PopulateServiceCollection(IServiceCollection services) { }

                public void ConfigureServices(IServiceCollection services) => services.AddSingleton(new Entry(name));
            }

            [AttributeUsage(AttributeTargets.All, AllowMultiple = true)]
            public sealed class NamedAttribute(string name) : Attribute, DependencyModules.Runtime.Interfaces.IDependencyModuleProvider
            {
                public DependencyModules.Runtime.Interfaces.IDependencyModule GetModule() => new NamedModule(name);
            }

            [AttributeUsage(AttributeTargets.All)]
            public sealed class DirectAttribute : Attribute, DependencyModules.Runtime.Interfaces.IDependencyModule, DependencyModules.Runtime.Interfaces.IServiceCollectionConfiguration
            {
                public void PopulateServiceCollection(IServiceCollection services) { }

                public void ConfigureServices(IServiceCollection services) => services.AddSingleton(new Entry("direct"));
            }

            public sealed class SutModule : DependencyModules.Runtime.Interfaces.IDependencyModule, DependencyModules.Runtime.Interfaces.IServiceCollectionConfiguration
            {
                public void PopulateServiceCollection(IServiceCollection services) { }

                public void ConfigureServices(IServiceCollection services) => services.AddSingleton(new Entry("sut"));
            }
        }

        """;

    [VerifyTest]
    [Row("[assembly: ServiceCollection] public partial class OrderTests { [VerifyTest] public void Pays() { } }")]
    [Row("[ServiceCollection] public partial class OrderTests { [VerifyTest] public void Pays() { } }")]
    [Row("[ServiceCollection<Services>] public partial class OrderTests { [VerifyTest] public void Pays() { } }")]
    public void Without_DependencyModules_the_generated_code_names_no_DependencyModules_type(string source)
    {
        var compilation = GeneratorHarness.Compilation(
            GeneratorHarness.Usings + source,
            "public sealed class Services { public static void Configure(IServiceCollection services) { } }");
        var driver = CSharpGeneratorDriver.Create([new TestGenerator().AsSourceGenerator(), new ConfigureGenerator().AsSourceGenerator()], parseOptions: GeneratorHarness.ParseOptions)
            .RunGeneratorsAndUpdateCompilation(compilation, out var output, out _, CancellationToken.None);

        var generated = driver.GetRunResult().GeneratedTrees;
        Assert.NotEmpty(generated);
        Assert.DoesNotContain(generated, tree => tree.ToString().Contains("DependencyModules", StringComparison.Ordinal));
        Assert.Empty(output.GetDiagnostics().Where(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error));
    }

    [VerifyTest]
    public void With_DependencyModules_the_source_reads_the_attributes_from_the_method_back_to_the_assembly()
    {
        var (run, output) = GeneratorHarness.Run("[ServiceCollection<Shop.SutModule>] public partial class OrderTests { }", Modules, GeneratorHarness.DependencyModulesRuntime);

        Assert.Empty(run.Diagnostics);
        Assert.Contains(
            "global::VerificationGlue.Tests.DependencyInjection.ServiceCollectionRegistry.Register<global::Shop.SutModule>(static (services, context) => { });",
            Tree(run, ConfigureGenerator.HintName));
        Assert.Equal(
            """
            // <auto-generated/>
            #nullable enable
            #pragma warning disable
            namespace VerificationGlue.Tests.DependencyInjection.Generated
            {
                internal static class DependencyModulesSource
                {
                    [global::System.Runtime.CompilerServices.ModuleInitializer]
                    internal static void Register() =>
                        global::VerificationGlue.Tests.DependencyInjection.ServiceCollectionRegistry.AddSource(AddModules);

                    // AddModules inserts each module before the ones it has, so the attributes are read from the
                    // method back to the assembly, and the method's modules are applied last.
                    private static void AddModules(global::Microsoft.Extensions.DependencyInjection.IServiceCollection services, global::System.Collections.Generic.IReadOnlyList<global::System.Attribute> attributes)
                    {
                        var modules = new global::System.Collections.Generic.List<global::DependencyModules.Runtime.Interfaces.IDependencyModule>();
                        for (var i = attributes.Count - 1; i >= 0; i--)
                        {
                            switch (attributes[i])
                            {
                                case global::VerificationGlue.Tests.DependencyInjection.ServiceCollectionAttribute<global::Shop.SutModule>:
                                    modules.Add(new global::Shop.SutModule());
                                    break;
                                case global::DependencyModules.Runtime.Interfaces.IDependencyModuleProvider provider:
                                    modules.Add(provider.GetModule());
                                    break;
                                case global::DependencyModules.Runtime.Interfaces.IDependencyModule module:
                                    modules.Add(module);
                                    break;
                            }
                        }

                        if (modules.Count > 0)
                        {
                            global::DependencyModules.Runtime.ServiceCollectionExtensions.AddModules(services, modules.ToArray());
                        }
                    }
                }
            }

            """.ReplaceLineEndings("\n"),
            Tree(run, ConfigureGenerator.ModulesHintName));
        Assert.Empty(output.GetDiagnostics().Where(diagnostic => diagnostic.Severity >= DiagnosticSeverity.Warning));
    }

    [VerifyTest]
    [Row("[ServiceCollection] public partial class OrderTests { }")]
    [Row("[assembly: ServiceCollection]")]
    public void The_plain_attribute_writes_the_source_with_no_module_type(string source)
    {
        var (run, output) = GeneratorHarness.Run(source, Modules, GeneratorHarness.DependencyModulesRuntime);

        Assert.DoesNotContain("case global::VerificationGlue", Assert.Single(run.GeneratedTrees).ToString(), StringComparison.Ordinal);
        Assert.Empty(output.GetDiagnostics().Where(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error));
    }

    [VerifyTest]
    public void Without_a_ServiceCollection_attribute_nothing_is_written()
    {
        var (run, _) = GeneratorHarness.Run("public partial class OrderTests { }", Modules, GeneratorHarness.DependencyModulesRuntime);

        Assert.Empty(run.GeneratedTrees);
    }

    [VerifyTest]
    public void A_class_marked_DependencyModule_is_a_module()
    {
        var (run, _) = GeneratorHarness.Run(
            "[ServiceCollection<Shop.Marked>] public partial class OrderTests { }",
            "namespace Shop { [DependencyModules.Runtime.Attributes.DependencyModule] public partial class Marked { } }",
            GeneratorHarness.DependencyModulesRuntime);

        Assert.Empty(run.Diagnostics);
        Assert.Contains("modules.Add(new global::Shop.Marked());", Tree(run, ConfigureGenerator.ModulesHintName), StringComparison.Ordinal);
    }

    [VerifyTest]
    public void A_type_with_Configure_that_is_also_a_module_is_called_through_Configure()
    {
        var (run, _) = GeneratorHarness.Run(
            "[ServiceCollection<Shop.Both>] public partial class OrderTests { }",
            "namespace Shop { [DependencyModules.Runtime.Attributes.DependencyModule] public partial class Both { public static void Configure(IServiceCollection services) { } } }",
            GeneratorHarness.DependencyModulesRuntime);

        Assert.Contains("global::Shop.Both.Configure(services)", Tree(run, ConfigureGenerator.HintName), StringComparison.Ordinal);
        Assert.DoesNotContain("Both", Tree(run, ConfigureGenerator.ModulesHintName), StringComparison.Ordinal);
    }

    /// <summary>
    /// The container's attributes come from the assembly, then the class, then the method. Each module's
    /// registration is applied in that order, so the method's comes last and wins.
    /// </summary>
    [VerifyTest]
    public void The_modules_are_applied_from_the_assembly_to_the_method_in_one_AddModules_call()
    {
        var (_, output) = GeneratorHarness.Run("[ServiceCollection<Shop.SutModule>] public partial class OrderTests { }", Modules, GeneratorHarness.DependencyModulesRuntime);
        var assembly = Assembly.Load(GeneratorHarness.Emit(output));
        RuntimeHelpers.RunModuleConstructor(assembly.ManifestModule.ModuleHandle);
        Attribute Named(string name) => (Attribute)Activator.CreateInstance(assembly.GetType("Shop.NamedAttribute", throwOnError: true)!, name)!;
        var sut = (Attribute)Activator.CreateInstance(assembly.GetType("VerificationGlue.Tests.DependencyInjection.ServiceCollectionAttribute`1", throwOnError: true)!
            .MakeGenericType(assembly.GetType("Shop.SutModule", throwOnError: true)!))!;
        var direct = (Attribute)Activator.CreateInstance(assembly.GetType("Shop.DirectAttribute", throwOnError: true)!)!;
        IReadOnlyList<Attribute> attributes = [Named("assembly"), sut, new ObsoleteAttribute(), Named("class 1"), Named("class 2"), direct, Named("method")];

        var services = new ServiceCollection();
        assembly.GetType("VerificationGlue.Tests.DependencyInjection.Generated.DependencyModulesSource", throwOnError: true)!
            .GetMethod("AddModules", BindingFlags.NonPublic | BindingFlags.Static)!
            .Invoke(null, [services, attributes]);

        var entries = services.Where(service => service.ServiceType.Name == "Entry").Select(service => service.ImplementationInstance!.ToString()).ToArray();
        Assert.Equal(
            ["Entry { Name = assembly }", "Entry { Name = sut }", "Entry { Name = class 1 }", "Entry { Name = class 2 }", "Entry { Name = direct }", "Entry { Name = method }"],
            entries);
    }

    private static string Tree(GeneratorDriverRunResult run, string hintName) =>
        run.Results.SelectMany(result => result.GeneratedSources).Single(source => source.HintName == hintName).SourceText.ToString();
}
