using System.Runtime.CompilerServices;
using Microsoft.CodeAnalysis;
using Microsoft.Extensions.DependencyInjection;

namespace VerificationGlue.Tests.DependencyInjection.Generator.Specs;

public class ConfigureSpecs
{
    private const string Sources = """
        namespace Shop
        {
            public interface IClock { }
            public sealed class SystemClock : IClock { }

            public sealed class ShopServices
            {
                public static void Configure(IServiceCollection services) => services.AddSingleton<IClock, SystemClock>();
            }

            public sealed class PaymentServices
            {
                public static void Configure(IServiceCollection services, TestContainerContext context) => services.AddSingleton<SystemClock>();
            }
        }

        """;

    [VerifyTest]
    public void Each_type_on_the_assembly_a_class_or_a_method_is_registered_once()
    {
        var (run, output) = GeneratorHarness.Run("""
            [assembly: ServiceCollection<Shop.ShopServices>]

            [ServiceCollection<Shop.ShopServices>]
            public partial class OrderTests
            {
                [VerifyTest]
                [ServiceCollection<Shop.PaymentServices>]
                public void Pays() { }
            }
            """,
            Sources);

        Assert.Empty(run.Diagnostics);
        Assert.Equal(
            """
            // <auto-generated/>
            #nullable enable
            #pragma warning disable
            namespace VerificationGlue.Tests.DependencyInjection.Generated
            {
                internal static class ServiceCollectionSources
                {
                    [global::System.Runtime.CompilerServices.ModuleInitializer]
                    internal static void Register()
                    {
                        global::VerificationGlue.Tests.DependencyInjection.ServiceCollectionRegistry.Register<global::Shop.PaymentServices>(static (services, context) => global::Shop.PaymentServices.Configure(services, context));
                        global::VerificationGlue.Tests.DependencyInjection.ServiceCollectionRegistry.Register<global::Shop.ShopServices>(static (services, context) => global::Shop.ShopServices.Configure(services));
                    }
                }
            }

            """.ReplaceLineEndings("\n"),
            Assert.Single(run.GeneratedTrees).ToString());
        Assert.Empty(output.GetDiagnostics().Where(diagnostic => diagnostic.Severity >= DiagnosticSeverity.Warning));
    }

    [VerifyTest]
    public void The_registration_calls_Configure()
    {
        var (_, output) = GeneratorHarness.Run("[ServiceCollection<Shop.ShopServices>] public partial class OrderTests { }", Sources);
        var assembly = System.Reflection.Assembly.Load(GeneratorHarness.Emit(output));
        RuntimeHelpers.RunModuleConstructor(assembly.ManifestModule.ModuleHandle);

        var source = assembly.GetType("VerificationGlue.Tests.DependencyInjection.ServiceCollectionSource`1")!
            .MakeGenericType(assembly.GetType("Shop.ShopServices")!);
        var configure = (Delegate)source.GetProperty("Configure")!.GetValue(null)!;
        var services = new ServiceCollection();
        configure.DynamicInvoke(services, null);

        Assert.Equal("Shop.IClock", Assert.Single(services).ServiceType.FullName);
    }

    [VerifyTest]
    public void The_plain_attribute_writes_no_file()
    {
        var (run, _) = GeneratorHarness.Run("[ServiceCollection] public partial class OrderTests { }");

        Assert.Empty(run.GeneratedTrees);
        Assert.Empty(run.Diagnostics);
    }

    [VerifyTest]
    public void A_Configure_on_a_base_type_is_called_on_the_named_type()
    {
        var (run, output) = GeneratorHarness.Run("""
            public class BaseServices { public static void Configure(IServiceCollection services) { } }
            public sealed class ShopServices : BaseServices { }
            [ServiceCollection<ShopServices>] public partial class OrderTests { }
            """);

        Assert.Empty(run.Diagnostics);
        Assert.Contains("global::ShopServices.Configure(services)", Assert.Single(run.GeneratedTrees).ToString(), StringComparison.Ordinal);
        Assert.Empty(output.GetDiagnostics().Where(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error));
    }
}
