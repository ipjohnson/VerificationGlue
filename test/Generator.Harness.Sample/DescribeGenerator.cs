using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Generator.Harness.Sample;

/// <summary>
/// Adds <c>public static string Describe()</c> to each partial class marked <c>[Describe]</c>. The
/// method returns the class name and its public property names, for example <c>Person(Name, Age)</c>.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class DescribeGenerator : IIncrementalGenerator
{
    public const string ModelStep = "DescribeModel";
    public const string AttributeName = "Generator.Harness.Sample.DescribeAttribute";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(output => output.AddSource(
            "DescribeAttribute.g.cs",
            """
            namespace Generator.Harness.Sample
            {
                [System.AttributeUsage(System.AttributeTargets.Class)]
                internal sealed class DescribeAttribute : System.Attribute
                {
                }
            }
            """));

        var models = context.SyntaxProvider
            .ForAttributeWithMetadataName(AttributeName, static (_, _) => true, static (attribute, _) => CreateModel((INamedTypeSymbol)attribute.TargetSymbol))
            .WithTrackingName(ModelStep);

        context.RegisterSourceOutput(models, static (output, model) => output.AddSource($"{model.HintName}.Describe.g.cs", Emit(model)));
    }

    private static DescribeModel CreateModel(INamedTypeSymbol type)
    {
        var properties = type.GetMembers()
            .OfType<IPropertySymbol>()
            .Where(property => property.DeclaredAccessibility == Accessibility.Public && !property.IsStatic)
            .Select(property => property.Name)
            .ToImmutableArray();

        var ns = type.ContainingNamespace.IsGlobalNamespace ? null : type.ContainingNamespace.ToDisplayString();
        return new DescribeModel(ns, type.Name, new EquatableArray<string>(properties));
    }

    private static SourceText Emit(DescribeModel model)
    {
        var text = new StringBuilder();
        text.Append("// <auto-generated/>\n");
        var indent = "";
        if (model.Namespace is not null)
        {
            text.Append("namespace ").Append(model.Namespace).Append("\n{\n");
            indent = "    ";
        }

        text.Append(indent).Append("partial class ").Append(model.Name).Append('\n');
        text.Append(indent).Append("{\n");
        text.Append(indent).Append("    public static string Describe() => \"")
            .Append(model.Name).Append('(').Append(string.Join(", ", model.Properties)).Append(")\";\n");
        text.Append(indent).Append("}\n");
        if (model.Namespace is not null)
        {
            text.Append("}\n");
        }

        return SourceText.From(text.ToString(), Encoding.UTF8);
    }
}
