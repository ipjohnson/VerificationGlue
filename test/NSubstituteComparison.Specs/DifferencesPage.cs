using System.Text;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace NSubstituteComparison.Specs;

/// <summary>Writes <c>docs/guide/nsubstitute-differences.md</c> from a comparison run and the case sources.</summary>
public static class DifferencesPage
{
    public const string PagePath = "docs/guide/nsubstitute-differences.md";

    private const string CasesPath = "test/NSubstituteComparison/Cases";

    public static string Render(IReadOnlyList<CaseResult> results, string nsubstituteVersion, string repositoryRoot)
    {
        var page = new StringBuilder();
        var differing = results.Count(result => result.Differs);
        var areas = results.GroupBy(result => result.Case.AreaTitle).ToList();

        page.Append("# Known differences from NSubstitute\n\n");
        page.Append("<!-- Generated by test/NSubstituteComparison.Specs. Run the specs with VERIFICATIONGLUE_ACCEPT_DIFFERENCES=1 to update it. -->\n\n");
        page.Append($"VerificationGlue.Mocks behaves like NSubstitute {nsubstituteVersion} in {results.Count - differing} of {results.Count} comparison cases. ");
        page.Append($"This page lists the other {differing} and the reason for each. ");
        page.Append("The [migration guide](migrate-from-nsubstitute.md) shows how to move a test project.\n\n");
        page.Append("Each case is one source file that compiles against both libraries. Only the `using` directives and `Mock.Of<T>()` change. ");
        page.Append("`test/NSubstituteComparison.Specs` runs every case under both libraries in CI. ");
        page.Append("It fails when a case differs without a recorded reason, when a recorded difference no longer differs, and when this page differs from the run.\n\n");

        page.Append("| Area | Cases | Differences |\n|---|---|---|\n");
        foreach (var area in areas)
        {
            var file = area.First().Case.Area + ".cs";
            page.Append($"| [{area.Key}](../../{CasesPath}/{file}) | {area.Count()} | {area.Count(result => result.Differs)} |\n");
        }

        page.Append($"| Total | {results.Count} | {differing} |\n\n");
        page.Append("The comparison is bounded to these areas. It does not cover members that only one library has, such as NSubstitute's `ReturnsForAnyArgs` and `Received.InOrder`.\n");

        foreach (var area in areas.Where(area => area.Any(result => result.Differs)))
        {
            page.Append($"\n## {area.Key}\n");
            foreach (var result in area.Where(result => result.Differs))
            {
                page.Append($"\n### {result.Case.Title}\n\n");
                page.Append(result.Case.Difference).Append("\n\n");
                page.Append("```cs\n").Append(CaseBody(repositoryRoot, result.Case)).Append("```\n\n");
                page.Append("| Observation | NSubstitute | VerificationGlue.Mocks |\n|---|---|---|\n");
                for (var i = 0; i < Math.Max(result.NSubstitute.Count, result.Glue.Count); i++)
                {
                    var nsubstitute = i < result.NSubstitute.Count ? result.NSubstitute[i] : null;
                    var glue = i < result.Glue.Count ? result.Glue[i] : null;
                    page.Append($"| {Code(nsubstitute?.Label ?? glue!.Label)} | {Code(nsubstitute?.Value)} | {Code(glue?.Value)} |\n");
                }
            }
        }

        return page.ToString();
    }

    /// <summary>The statements of the case method, without its braces and with the common indent removed.</summary>
    private static string CaseBody(string repositoryRoot, ComparisonCase @case)
    {
        var path = Path.Combine(repositoryRoot, CasesPath, @case.Area + ".cs");
        var root = CSharpSyntaxTree.ParseText(File.ReadAllText(path)).GetRoot();
        var method = root.DescendantNodes()
            .OfType<MethodDeclarationSyntax>()
            .Single(method => method.Identifier.ValueText == @case.Name && method.Parent is ClassDeclarationSyntax { Identifier.ValueText: var type } && type == @case.Area);

        var lines = method.Body!.Statements.ToFullString().Replace("\r\n", "\n").TrimEnd().Split('\n');
        var indent = lines.Where(line => line.Trim().Length > 0).Min(line => line.Length - line.TrimStart().Length);
        var body = new StringBuilder();
        foreach (var line in lines.SkipWhile(line => line.Trim().Length == 0))
        {
            body.Append(line.Length >= indent ? line[indent..] : line.TrimStart()).Append('\n');
        }

        return body.ToString();
    }

    private static string Code(string? text) => text is null ? "(none)" : "`" + text.Replace("|", "\\|") + "`";
}
